#!/usr/bin/env python3
"""Generate core/src/keep.rs to anchor IntoElement monomorphizations in the cdylib.

Reads element types from core/data/components.json and picks a public module path
for each non-generic element using core/keep-choice.json. Pass --errors <rustc-log>
to advance failed paths to their next candidate module path.
"""

import re
import sys
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
cat = json.load(open(os.path.join(here, "data/components.json")))
choice_path = os.path.join(here, "keep-choice.json")
choice = json.load(open(choice_path)) if os.path.exists(choice_path) else {}

# Build candidate re-export paths from broadest (crate root) to deepest module path.
CRATE = {"gpui_base": "gpui_kit::base", "gpui_component": "gpui_kit::component"}
types = {}
for t in cat["types"]:
    if t["role"] != "element" or t["generics"] or "IntoElement" not in t["traits"]:
        continue
    if t["crate"] not in CRATE:
        continue
    root = CRATE[t["crate"]]
    module = t["module"].replace("/", "::")
    cands = [f"{root}::{t['name']}"]
    parts = module.split("::") if module else []
    for n in range(len(parts), 0, -1):
        cands.append(f"{root}::{'::'.join(parts[:n])}::{t['name']}")
    types[f"{t['crate']}::{t['module']}::{t['name']}"] = cands
keys = sorted(types)

def lines():
    """Return (type_key, selected_path) pairs for types with a remaining candidate."""
    out = []
    for k in keys:
        c = choice.get(k, 0)
        if c < len(types[k]):
            out.append((k, types[k][c]))
    return out

# Map compiler error line numbers back to type indices (first entry starts at line 10).
if "--errors" in sys.argv:
    log = open(sys.argv[sys.argv.index("--errors") + 1]).read()
    bad = {int(m) for m in re.findall(r"capi/src/keep\.rs:(\d+):", log)}
    current = lines()
    FIRST = 10
    moved = 0
    for i, (k, _) in enumerate(current):
        if FIRST + i in bad:
            choice[k] = choice.get(k, 0) + 1
            moved += 1
    json.dump(choice, open(choice_path, "w"), indent=0, sort_keys=True)
    print(f"keep: {moved} types moved to their next candidate")

kept = lines()
out = ["// Generated by core/gen-keep.py from core/data/components.json. Do not edit.",
       f"// {len(kept)} element types kept, {len(keys) - len(kept)} skipped (no public path found by rule).",
       "use gpui_kit::{AnyElement, IntoElement};", "use std::hint::black_box;", "",
       "/// Never called with a useful result: it exists so the linker keeps every render path.",
       "#[unsafe(no_mangle)]", "pub extern \"C\" fn gk_keep_all() -> usize {", "    let mut n = 0usize;"]
for _, p in kept:
    out.append(f"    n += black_box(<{p} as IntoElement>::into_any_element as fn({p}) -> AnyElement) as usize;")
out += ["    n", "}", ""]
open(os.path.join(here, "src/keep.rs"), "w").write("\n".join(out))
print(f"keep.rs: {len(kept)} kept, {len(keys) - len(kept)} skipped")
