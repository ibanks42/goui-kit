#!/usr/bin/env python3
"""Writes the three opcode tables from wire/ops.txt (standard library only).

    python3 core/wire/gen.py          # rewrites the generated files in place
    python3 core/wire/gen.py --check  # exit 1 if a generated file is stale
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
src = open(os.path.join(here, "ops.txt"), "rb").read()

PREFIX = {"abi": "ABI_", "feat": "FEAT_", "kind": "K_", "err": "ERR_", "hkind": "HK_",
          "node": "N_", "elop": "E_", "style": "S_", "color": "COLOR_", "theme": "T_",
          "call": "C_", "shape": "SHAPE_"}

rows = []
for line in src.decode().splitlines():
    line = line.split("#")[0].strip()
    if not line:
        continue
    cls, name, num = line.split()
    rows.append((cls, name, int(num)))

seen = {}
for cls, name, num in rows:
    if cls in ("abi",):
        continue
    key = (cls, num)
    if key in seen and cls != "feat":
        sys.exit(f"ops.txt: {cls} {name} reuses number {num} of {seen[key]}")
    seen[key] = name

# FNV-1a 64 of this file's bytes and of the generator's numbers: a library and a package
# generated from different tables refuse each other at start.
lock = open(os.path.join(root, "api", "opcodes.lock"), "rb").read()
h = 0xCBF29CE484222325
for b in src + lock:
    h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF

HEAD = "Generated by core/wire/gen.py from core/wire/ops.txt. Do not edit."


def pascal(name):
    return "".join(p.capitalize() for p in name.split("_"))


def ada(name):
    return "_".join(p.capitalize() for p in name.split("_"))


def rust():
    o = [f"// {HEAD}", "#![allow(dead_code)]", f"pub const API_HASH: u64 = {h:#018x};"]
    for cls, name, num in rows:
        ty = {"abi": "u16", "feat": "u32", "kind": "u32", "err": "i32", "hkind": "u8",
              "color": "u8", "call": "u16"}.get(cls, "u16")
        o.append(f"pub const {PREFIX[cls]}{name}: {ty} = {num};")
    return "\n".join(o) + "\n"


def go():
    o = [f"// Code generated by core/wire/gen.py from core/wire/ops.txt. DO NOT EDIT.", "", "package rt", "",
         f"const ApiHash uint64 = {h:#018x}", ""]
    for cls, name, num in rows:
        if cls == "style":
            continue
        pre = PREFIX[cls].lower().rstrip('_')
        o.append(f"const {pre[:1].upper() + pre[1:]}{pascal(name)} = {num}")
    return "\n".join(o) + "\n"


def go_s():
    o = [f"// {HEAD}", "",
         "// Package s holds the style tokens: the nullary Styled methods of GPUI, by upstream's",
         "// names. gk.VFlex(s.SizeFull, s.Gap3).", "package s", "",
         "// Token is one nullary Styled method.", "type Token uint16", ""]
    for cls, name, num in rows:
        if cls == "style":
            o.append(f"const {pascal(name)} Token = {num}")
    return "\n".join(o) + "\n"


def header():
    o = [f"/* {HEAD} */", "#ifndef GK_OPS_H", "#define GK_OPS_H", f"#define GK_API_HASH {h:#018x}ull"]
    cname = {"abi": "GK_ABI_", "feat": "GK_FEAT_", "kind": "GK_KIND_", "err": "GK_ERR_",
             "hkind": "GK_HKIND_", "node": "GK_NODE_", "elop": "GK_OP_", "style": "GK_STYLE_",
             "color": "GK_COLOR_", "theme": "GK_THEME_", "call": "GK_CALL_", "shape": "GK_SHAPE_"}
    for cls, name, num in rows:
        o.append(f"#define {cname[cls]}{name} {num}")
    o.append("#endif")
    return "\n".join(o) + "\n"


out = {
    "core/src/ops.rs": rust(),
    "core/include/gk_ops.h": header(),
    # The Go front end (docs/GO.md): the same numbers; the style tokens are the generator's
    # (go/gk/s, gen/gk_go.py), so go_s() is not written.
    "go/gk/internal/rt/gen_ops.go": go(),
    # cgo compiles against the same header the library was built with: a copy inside the package,
    # so `go build` needs no include path.
    "go/gk/internal/rt/include/gk_ops.h": header(),
    "go/gk/internal/rt/include/gpuikit.h": open(os.path.join(root, "core", "include", "gpuikit.h")).read(),
}
stale = 0
for rel, text in out.items():
    path = os.path.join(root, rel)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        if "--check" in sys.argv:
            print("stale:", rel)
            stale = 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
            print("wrote", rel)
sys.exit(stale)
