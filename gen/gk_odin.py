SUPPORT = '''// Generated by gen/gkgen.py. Do not edit. What every generated file shares: the layout of a
// node type, values that are not elements, and the Odin side of gpui's own value types.
// It uses the emitter interface of the runtime (docs/PROTOCOLS.md section 7) and, for
// take, node_args and new_value, the build in progress itself (build.nodes, build.ops).
package gk

// Any_El is the layout of every node type: shared trait tables are written against it.
Any_El :: struct {
	using el: Element,
	vt:       rawptr,
}

// Value is a builder value that is not an element (a column, a menu item, a style).
Value :: struct {
	node, serial: u32,
}

@(private)
vel :: #force_inline proc(v: Value) -> Element {
	return {v.node, v.serial}
}

@(private)
new_value :: proc(typ: u16, loc := #caller_location) -> Value {
	if !build.active {
		return value_new(typ, loc) // outside a view: a call op's argument (rt_handles.odin)
	}
	e := new_node(typ, loc)
	return {e.node, e.serial}
}

// node_args is the op stream, placed where the node made last keeps its constructor arguments.
@(private)
node_args :: proc() -> ^Tape {
	if !build.active {
		return value_args()
	}
	build.nodes[len(build.nodes) - 1].args = u32(len(build.ops))
	return &build.ops
}

// take uses an element as an argument: once, in the build that made it. A method that
// changes the type (div()->id(..)) takes its own receiver.
@(private)
take :: proc(e: Element, receiver := false) -> u32 {
	if e.serial != build.serial || !build.active {
		stop({}, "an element was used after the view procedure that made it returned: an element lives for one call of the view procedure. Make it again in each call (a procedure that returns the element is how a piece of a view is reused)%s", element_origin(e.node, false))
	}
	if build.nodes[e.node].attached {
		stop({}, "an element was given to a second builder: an element has one place in a view. Make another one for the second place (a procedure that returns it, called twice)%s", element_origin(e.node, true))
	}
	if e.node == build.cur && !receiver {
		// The library would decode the node inside itself until its stack ran out.
		stop({}, "an element was given as an argument to its own builder (x->child(x) or the like)%s", element_origin(e.node, true))
	}
	build.nodes[e.node].attached = true
	return e.node
}

// take_value uses a value that is not an element (a style, a column) as an argument. A value
// may be given to any number of builders of the build that made it: it is decoded each time,
// and it can no longer be changed once it has been used.
@(private)
take_value :: proc(v: Value) -> u32 {
	if !build.active && v.serial == vbuild.serial && vbuild.serial != 0 {
		return value_take(v) // a value made outside a view (rt_handles.odin)
	}
	if v.serial != build.serial || !build.active {
		stop({}, "a kit value (a column, a menu item, a style, a tooltip) was used after the view procedure that made it returned: values live for one call. Make it again in each call%s", element_origin(v.node, false))
	}
	if v.node == build.cur {
		stop({}, "a value was given as an argument to its own builder%s", element_origin(v.node, true))
	}
	build.nodes[v.node].attached = true
	return v.node
}

// put_usize writes an int where the kit takes a usize (a count, a size or an index). A
// negative one would arrive as a number near 2^64 and show wrong content with exit 0.
@(private)
put_usize :: proc(b: ^Tape, v: int) {
	if v < 0 {
		stop({}, "a negative number (%d) was given where the kit takes a count, size or index (usize): a builder of the element being described got it%s", v, element_origin(build.cur, true))
	}
	put_u64(b, u64(v))
}

// put_range writes a Range where the kit takes a Range<usize> (byte offsets, rows). A negative
// end would arrive near 2^64 (the kit clips it to the end of the text) instead of stopping, as
// a negative usize does.
@(private)
put_range :: proc(b: ^Tape, r: Range) {
	if r.lo < 0 || r.hi < 0 {
		stop({}, "a negative number was given in a range (%d ..< %d) where the kit takes byte offsets or indices (usize)%s", r.lo, r.hi, element_origin(build.cur, true))
	}
	put_u64(b, u64(r.lo))
	put_u64(b, u64(r.hi))
}

@(private)
rt_child_view :: proc(e: Any_El, v: View) -> Any_El {
	slot_view(e, v)
	return e
}

// focus_handle makes a focus handle (GPUI's FocusHandle): give it to track_focus on an
// element, and focus it with gk.focus.
focus_handle :: proc(cx: ^Cx, loc := #caller_location) -> Focus_Handle {
	return Focus_Handle{focus_new(cx, loc)}
}

// focus moves keyboard focus to the element that tracks the handle.
focus :: proc(cx: ^Cx, f: Focus_Handle, loc := #caller_location) {
	focus_set(cx, f.h, loc)
}

@(private)
rt_style :: proc(e: Any_El, flags: ..Style_Flag) -> Any_El {
	tokens(e, flags)
	return e
}

@(private)
rt_parent_text :: proc(e: Any_El, s: string) -> Any_El {
	put_str(op(e, OP_TEXT_N), s)
	return e
}

// theme is a colour of the kit's theme, resolved by the library each time it decodes.
theme :: proc(c: Theme_Color) -> Color {
	return {theme = u16(c)}
}

// palette is one of the kit's fixed colours (gk.palette(.Blue_500)).
palette :: proc(c: Palette) -> Color {
	return {theme = u16(c)}
}

// Length is what `impl Into<Length>`, DefiniteLength and AbsoluteLength accept.
Length :: struct {
	kind: u8,
	v:    f32,
}

px :: proc(v: f32) -> Length {return {0, v}}
rems :: proc(v: f32) -> Length {return {1, v}}
relative :: proc(v: f32) -> Length {return {2, v}}
auto :: proc() -> Length {return {3, 0}}

@(private)
put_length :: proc(b: ^Tape, l: Length) {
	put_u8(b, l.kind)
	put_f32(b, l.v)
}

// Upstream's DefiniteLength has no auto and its AbsoluteLength is px or rems only. Length is
// one type in Odin, so a kind the builder cannot take stops here; the library would read it
// as that many px.
@(private)
put_definite_length :: proc(b: ^Tape, l: Length) {
	if l.kind > 2 {
		stop({}, "gk.auto() was given to a builder that takes a definite length: give gk.px, gk.rems or gk.relative%s", element_origin(build.cur, true))
	}
	put_length(b, l)
}

@(private)
put_absolute_length :: proc(b: ^Tape, l: Length) {
	if l.kind > 1 {
		stop({}, "gk.relative or gk.auto was given to a builder that takes an absolute length: give gk.px or gk.rems%s", element_origin(build.cur, true))
	}
	put_length(b, l)
}

// A duration travels as whole milliseconds in a u32 (std::time::Duration has no negative
// values): rounded, a negative one is 0 and anything past 49 days is 49 days.
@(private)
put_ms :: proc(b: ^Tape, nanoseconds: i64) {
	ms := (max(nanoseconds, 0) + 500_000) / 1_000_000
	put_u32(b, u32(min(ms, i64(max(u32)))))
}

Named_Id :: struct {
	name: string,
	n:    u64,
}

// Id is what `impl Into<ElementId>` accepts: a name, a number, or both (gk.id("row", i)).
Id :: union #no_nil {
	string,
	int,
	Named_Id,
}

id :: proc(name: string, n: int) -> Id {
	return Named_Id{name, u64(n)}
}

@(private)
put_id :: proc(b: ^Tape, v: Id) {
	switch x in v {
	case string:
		put_u8(b, 0)
		put_str(b, x)
	case int:
		put_u8(b, 1)
		put_u64(b, u64(x))
	case Named_Id:
		put_u8(b, 2)
		put_str(b, x.name)
		put_u64(b, x.n)
	}
}

Range :: struct {
	lo, hi: int,
}

// Handle is a library object the app holds by number (a kit state, a focus handle).
Handle :: struct {
	h: u64,
}

// Action is an action of the app's action table (gk.action("people::AddRow")).
Action :: struct {
	id: u32,
}

@(private)
put_action :: proc(b: ^Tape, a: Action) {
	put_u32(b, a.id)
}
'''


def oname(name):
    return name + "_" if name in KEYWORDS else name


def sname(name):
    """A state or object method's name: also escapes the fields every such type has (`using state:
    State, using vt: ^T_VT`), which a method named state would shadow (PROTOCOLS.md 11.8)."""
    return name + "_" if name in ("state", "vt") else oname(name)


def pname(name):
    return name + "_" if name in KEYWORDS or name in LOCALS else name


class Odin:
    def __init__(self, m, outdir):
        self.m, self.out = m, outdir
        self.names = {}       # Odin identifier -> what owns it
        self.files, self.spans = {}, {}
        self.file, self.lines = None, []
        self.collisions = []
        self.tuples = {}
        self.handles = {}
        # Names the hand-written files of the package declare (the runtime, the bridges): a
        # generated type or procedure that would take one gets the crate prefix instead (a
        # library object TreeEntry beside the rows family's record Tree_Entry).
        for fn in sorted(os.listdir(outdir)) if os.path.isdir(outdir) else []:
            if fn.endswith(".odin") and not fn.startswith("gen_") and fn != "ops.odin":
                for name in re.findall(r"(?m)^(\w+)\s*::", open(os.path.join(outdir, fn)).read()):
                    self.names.setdefault(name, "hand " + fn)
        self.name_types()

    # ------------------------------------------------------------ names

    def claim(self, base, crate, key, lower=False):
        """A package-level name. Priority component, base, gpui; the loser gets a prefix."""
        pre = {"gpui_base": "Base_", "gpui": "Gpui_", "gpui_component": "Kit_", "gpui_kit": "Kit_"}[crate]
        cands = [base] if base not in RESERVED else []
        cands += [(pre.lower() if lower else pre) + base]
        for c in cands:
            c = oname(c)
            if c not in self.names:
                self.names[c] = key
                return c
        self.collisions.append((base, key, self.names.get(cands[-1])))
        n = 2
        while f"{cands[-1]}_{n}" in self.names:
            n += 1
        self.names[f"{cands[-1]}_{n}"] = key
        return f"{cands[-1]}_{n}"

    def name_types(self):
        m = self.m
        order = {"gpui_component": 0, "gpui_base": 1, "gpui": 2, "gpui_kit": 3}
        for key in sorted(m.nodes, key=lambda k: (order[m.nodes[k]["crate"]], k)):
            node = m.nodes[key]
            base = self.m.ov.get("rename", {}).get(node["name"], ada(node["name"]))
            node["odin"] = self.claim(base, node["crate"], key)
        for table in (m.enums, m.denums, m.records):
            for rt in sorted(table, key=lambda k: (order[table[k]["crate"]], k)):
                t = table[rt]
                base = ada(t["name"]) + "".join("_" + ada(a) for a in t.get("args", []) if a != "Pixels")
                t["odin"] = self.claim(base, t["crate"], rt)
        # A record a parameter may take as one field alone (PROTOCOLS.md 11.36): three unions,
        # named after upstream's type. The name the record's own builder node claimed is free
        # when that node is never emitted (IndexPath: its builders are value helpers).
        for rt in sorted(m.records):
            rc = m.records[rt]
            if not rc.get("shorthand"):
                continue
            base = ada(rc["name"])
            node = m.nodes.get(rt)
            if self.names.get(base) == rt and node is not None and not any(
                    i["status"] in ("bound", "bridged") for i in node["ctors"] + node.get("ops", [])):
                del self.names[base]
            rc["short_odin"] = {how: self.claim(name, rc["crate"], f"shorthand {how} {rt}") for how, name in
                                (("one", base), ("opt", "Maybe_" + base), ("list", base + "_List"))}
        for key in sorted(m.states, key=lambda k: (order[m.states[k]["crate"]], k)):
            st = m.states[key]
            if st.get("obj"):
                # A library object (PROTOCOLS.md section 13): named when the app can get one.
                if not st.get("reachable"):
                    continue
                st["odin"] = self.claim(ada(st["name"]), st["crate"], "state " + key)
                low = st["odin"].lower()
                for it in sorted(st["globals"] + st["statics"], key=lambda i: i["id"]):
                    if it["status"] == "bridged":
                        it["odin"] = self.claim(f"{low}_{it['name']}", st["crate"], it["id"], lower=True)
            elif not any(i["status"] == "bridged" for i in st["ctors"]) and not st.get("handed"):  # 11.8
                continue
            else:
                st["odin"] = self.claim(ada(st["name"]), st["crate"], "state " + key)
            for it in sorted(st["ctors"], key=lambda i: i["id"]):
                if it["status"] == "bridged":
                    base = st["odin"].lower() + ("" if it["name"] == "new" else "_" + it["name"])
                    it["odin"] = self.claim(base, st["crate"], it["id"], lower=True)
        for rt in sorted(m.intos):
            s = m.intos[rt]
            if len(s["members"]) > 1:
                s["odin"] = self.claim(ada(s["name"]) + "_Into", "gpui_kit", "into " + rt)
        for key in sorted(m.traits, key=lambda k: (order[m.traits[k]["crate"]], m.traits[k]["key"] or "")):
            t = m.traits[key]
            if t["ops"]:
                t["odin"] = self.claim(ada(t["name"]) + "".join("_" + ada(x) for x in t["extra"]) + "_Trait",
                                       t["crate"], "trait " + t["key"])
                t["low"] = t["odin"][:-6].lower()
        for key in sorted(m.nodes, key=lambda k: (order[m.nodes[k]["crate"]], k)):
            node = m.nodes[key]
            for it in sorted(node["ctors"], key=lambda i: i["id"]):
                if it["status"] not in ("bound", "bridged") or it["kind"] == "convert":
                    continue
                if it.get("free"):
                    base = it["name"]
                elif it["name"] == "new":
                    base = node["odin"].lower()
                else:
                    owner = m.nodes.get(it["owner"], node)["odin"].lower() if it["owner"] in m.nodes else node["odin"].lower()
                    base = f"{owner}_{it['name']}"
                it["odin"] = self.claim(base, it["crate"], it["id"], lower=True)
        gk_app.odin_names(self)  # the app family's ambient calls (PROTOCOLS.md section 11.5)

    # ------------------------------------------------------------ types and wire writers

    def otype(self, d, out=False):
        """The Odin type of a descriptor; out=True for a value read from the wire by reflection."""
        m, k = self.m, d[0]
        pt = gk_app.odin_type(self, d, out)  # the platform family's PROTOCOLS.md 13.31
        if pt:
            return pt
        et = gk_editor.odin_type(self, d, out)  # the editor family's PROTOCOLS.md 9.20 to 9.24
        if et:
            return et
        lt = gk_lists.odin_type(self, d, out)
        if lt:
            return lt
        if k == "dock":
            return gk_overlay.odin_dock_type(self, d, out)  # PROTOCOLS.md 11.8
        if k in gk_values.CALL_SAFE or k in gk_values.DEC_ONLY:
            return gk_values.odin_type(self, d, out)  # PROTOCOLS.md 13.9, 13.10
        if k == "bool":
            return "bool"
        if k == "int":
            return {"usize": "int", "isize": "int"}.get(d[1], d[1])
        if k in ("f32", "f64"):
            return k
        if k == "str":
            return "Temp_String" if out else "string"
        if k == "leaf":
            if out and d[1] == "color":
                return "Hsla"
            if gk_model.is_fill(d):
                return "Fill"  # a colour or a gradient (rt_emit.odin, PROTOCOLS.md 11.38)
            return {"px": "f32", "rems": "f32", "color": "Color", "length": "Length", "definite_length": "Length",
                    "absolute_length": "Length", "id": "Id", "duration": "time.Duration", "range": "Range",
                    "click_event": "Click_Event", "key_event": "Key_Event", "mouse_event": "Mouse_Event"}[d[1]]
        if k == "enum":
            return m.enums[d[1]]["odin"]
        if k == "denum":
            return m.denums[d[1]]["odin"]
        if k == "rec":
            return m.records[d[1]]["odin"]
        if k == "into":
            return m.intos[d[1]]["odin"]
        if k in ("ref", "from"):
            return self.otype(d[1], out)
        if k == "opt":
            return f"Maybe({self.otype(d[1], out)})"
        if k == "list":
            return f"[]{self.otype(d[1], out)}"
        if k == "tuple":
            ts = [self.otype(x, out) for x in d[1]]
            name = "Tuple_" + "_".join(re.sub(r"\W+", "", t.title()) for t in ts)
            self.tuples[name] = ts
            return name
        if k in ("child", "fragment"):
            return "Element"
        if k == "viewbuild":
            return gk_overlay.odin_type(self, d)  # PROTOCOLS.md 11.6
        if k == "panelview":
            return gk_overlay.odin_panel_type(self, d)  # a dock panel (PROTOCOLS.md 11.7)
        if k == "result":
            return "Maybe(Temp_String)"  # Result<(), E>: the error's text (PROTOCOLS.md 11.6)
        if k in ("node", "build", "stylefn"):
            return m.nodes[d[1]]["odin"]
        if k in ("shim", "rows", "datum_rows"):
            return "Row_Source"  # the delegate the library makes over it (PROTOCOLS.md 9.5)
        if k == "entity" and "odin" in m.states.get(d[1], {}):
            return m.states[d[1]]["odin"]
        if k == "obj":
            return m.states[d[2]]["odin"]
        if k == "refmut":
            return self.otype(d[1], out)
        if k in ("entity", "handle"):
            name = ada(d[2])
            if self.names.get(name, "handle " + d[1]) != "handle " + d[1]:
                name += "_Handle"
            self.names[name] = "handle " + d[1]
            self.handles[name] = d[1]
            return name
        if k == "action":
            return "Action_Handler" if d[1] == "listener" else "Action"
        if k == "handler":
            return "Handler"
        if k == "data":
            return "Data"  # gk.data(rows[:]): a slice of the app's own structs (rt_data.odin)
        if k in ("field", "format"):
            return "string"  # a column's name, or a template (PROTOCOLS.md section 12)
        raise KeyError(k)

    def put(self, d, v, depth=0):
        """Statements that write the value `v` of this descriptor to the op stream `o`."""
        m, k = self.m, d[0]
        pp = gk_app.odin_put(self, d, v)  # the platform family's PROTOCOLS.md 13.31
        if pp:
            return pp
        ep = gk_editor.odin_put(self, d, v)  # the editor family's PROTOCOLS.md 9.20 to 9.24
        if ep:
            return ep
        lp = gk_lists.odin_put(self, d, v)
        if lp:
            return lp
        if k == "dock":
            return gk_overlay.odin_dock_put(self, d, v)  # PROTOCOLS.md 11.8
        if k in gk_values.CALL_SAFE or k in gk_values.DEC_ONLY:
            return gk_values.odin_put(self, d, v, depth)  # PROTOCOLS.md 13.10
        if k == "bool":
            return [f"put_u8(o, u8({v}))"]
        if k == "int":
            if d[1] == "usize":
                return [f"put_usize(o, {v})"]  # an Odin int: a negative one is refused, not wrapped
            w = INT_WIRE[d[1]]
            return [{"u8": f"put_u8(o, u8({v}))", "i8": f"put_u8(o, u8({v}))", "u16": f"put_u16(o, u16({v}))",
                     "i16": f"put_u16(o, u16({v}))", "u32": f"put_u32(o, u32({v}))", "i32": f"put_u32(o, u32({v}))",
                     "u64": f"put_u64(o, u64({v}))", "i64": f"put_u64(o, u64({v}))"}[w]]
        if k == "f32":
            return [f"put_f32(o, {v})"]
        if k == "f64":
            return [f"put_u64(o, transmute(u64)f64({v}))"]
        if k == "str":
            return [f"put_str(o, {v})"]
        if k == "leaf":
            if gk_model.is_fill(d):
                return [f"put_fill(o, {v})"]
            return {"px": [f"put_f32(o, {v})"], "rems": [f"put_f32(o, {v})"], "color": [f"put_color(o, {v})"],
                    "length": [f"put_length(o, {v})"], "definite_length": [f"put_definite_length(o, {v})"],
                    "absolute_length": [f"put_absolute_length(o, {v})"], "id": [f"put_id(o, {v})"],
                    "duration": [f"put_ms(o, i64({v}))"],
                    "range": [f"put_range(o, {v})"]}[d[1]]
        if k == "enum":
            return [f"put_u16(o, u16({v}))"]
        if k in ("denum", "rec", "into"):
            return [f"put_{self.otype(d)}(o, {v})"]
        if k in ("ref", "from"):
            return self.put(d[1], v, depth)
        if k == "opt":
            x = f"x{depth}"
            return [f"if {x}, ok := {v}.?; ok {{", "\tput_u8(o, 1)"] + ["\t" + s for s in self.put(d[1], x, depth + 1)] + \
                ["} else {", "\tput_u8(o, 0)", "}"]
        if k == "list":
            x = f"x{depth}"
            return [f"put_u32(o, u32(len({v})))", f"for {x} in {v} {{"] + \
                ["\t" + s for s in self.put(d[1], x, depth + 1)] + ["}"]
        if k == "tuple":
            out = []
            for n, x in enumerate(d[1]):
                out += self.put(x, f"{v}.v{n}", depth)
            return out
        if k in ("child", "fragment"):
            return [f"put_u32(o, take({v}))"]
        if k == "viewbuild":
            return gk_overlay.odin_put(self, d, v)  # PROTOCOLS.md 11.6
        if k in ("node", "build", "stylefn"):
            if not m.nodes[d[1]]["element"]:
                if getattr(self, "in_call", False):
                    return [f"put_vtape(o, {v}.nd)"]  # a call op's argument: a tape of its own (PROTOCOLS.md 13.6)
                return [f"put_u32(o, take_value({v}.nd))"]
            return [f"put_u32(o, take({self.as_el(m.nodes[d[1]], v)}))"]
        if k == "obj" and not getattr(self, "in_call", False):
            return [f"put_obj(o, {v}.h)"]  # pinned to the view that places it (PROTOCOLS.md 13.12)
        if k in ("entity", "handle", "shim", "rows", "datum_rows", "obj", "panelview"):
            return [f"put_u64(o, {v}.h)"]
        if k == "refmut":
            return self.put(d[1], v, depth)
        if k == "action":
            return [f"put_action_handler(o, {v})" if d[1] == "listener" else f"put_action(o, {v})"]
        if k == "handler":
            return [f"put_u32(o, register({v}, {m.shapes[d[1]]['num']}))"]
        if k == "data":
            return [f"put_data(o, {v})"]
        if k == "field":
            return [f"put_field(o, {v}, .{ada(d[1])})"]
        if k == "format":
            nums = sum(1 for f in d[5] if f[0] in ("f32", "f64", "int"))
            row = "true" if any(f[0] == "datum" for f in d[5]) else "false"
            return [f"put_format(o, {v}, {nums}, {row})"]
        raise KeyError(k)

    @staticmethod
    def as_el(node, v):
        return f"{v}.el" if node["element"] else f"vel({v}.nd)"

    # ------------------------------------------------------------ files

    def open(self, name, doc):
        self.file, self.lines = name, ["// Generated by gen/gkgen.py. Do not edit. " + doc, "package gk", ""]
        self.spans[name] = []

    def add(self, *lines):
        self.lines += lines

    def item(self, key, lines):
        """Lines that belong to one item: a compiler error inside them is charged to it."""
        a = len(self.lines) + 1
        self.lines += lines
        self.spans[self.file].append((a, len(self.lines), key))

    def close(self):
        text = "\n".join(self.lines) + "\n"
        if "time." in text and 'import "core:time"' not in text:
            text = text.replace("package gk\n", 'package gk\n\nimport "core:time"\n', 1)
        self.files[self.file] = text

    def params(self, it, extra=()):
        ps = [f"{pname(a['name'])}: {self.ptype(a['desc'])}" for a in it["args"] if a["desc"][0] != "ctx"]
        return list(extra) + ps

    def shorthand(self, d):
        """(record, how) when a parameter of this descriptor may take the record's shorthand
        field alone (overrides [shorthand], PROTOCOLS.md 11.36); how is one, opt or list."""
        how = "one"
        while d[0] in ("ref", "from", "refmut"):
            d = d[1]
        if d[0] in ("opt", "list"):
            how, d = d[0], d[1]
            while d[0] in ("ref", "from"):
                d = d[1]
        if d[0] == "rec" and self.m.records[d[1]].get("short_odin"):
            return self.m.records[d[1]], how
        return None

    def ptype(self, d):
        """A parameter's Odin type: the descriptor's, or the union of a shorthand record."""
        sh = self.shorthand(d)
        return sh[0]["short_odin"][sh[1]] if sh else self.otype(d)

    def pput(self, d, v):
        """Writes a parameter: a shorthand union is first made the record (or its option or
        list) the descriptor's own writer takes, so the wire does not change."""
        sh = self.shorthand(d)
        if not sh:
            return self.put(d, v)
        rc, how = sh
        R, f, r = rc["odin"], oname(rc["shorthand"]), f"{v}_rec"
        decl = {"one": f"{r}: {R}", "opt": f"{r}: Maybe({R})", "list": f"{r}: []{R}"}[how]
        if how == "list":
            cases = [f"case []int:", f"\t{r} = make([]{R}, len(x), context.temp_allocator)",
                     f"\tfor {v}_n, {v}_i in x {{{r}[{v}_i] = {{{f} = {v}_n}}}}", f"case []{R}:", f"\t{r} = x"]
        else:
            cases = ["case int:", f"\t{r} = {R}{{{f} = x}}", f"case {R}:", f"\t{r} = x"]
        return [decl, f"switch x in {v} {{"] + cases + ["}"] + self.put(d, r)

    def body(self, it):
        out = []
        # A call op (kit state, a library object, an ambient call) takes a value made outside a
        # view as a tape of its own (PROTOCOLS.md 13.6); an element's op takes its node number.
        k = it.get("kind") or ""
        prev, self.in_call = getattr(self, "in_call", False), k.startswith(("state-", "obj-")) or k == "ambient"
        try:
            for a in it["args"]:
                if a["desc"][0] != "ctx":
                    out += self.pput(a["desc"], pname(a["name"]))
        finally:
            self.in_call = prev
        return out

    def emit(self):
        m = self.m
        bound = lambda i: i["status"] in ("bound", "bridged")  # noqa: E731
        # ---- nodes, per upstream module
        groups = {}
        for key in sorted(m.nodes):
            node = m.nodes[key]
            if any(bound(i) for i in node["ctors"]):
                fname = f"gen_{SHORT[node['crate']]}_{re.sub(r'[^a-z0-9]+', '_', node['module'].lower()) or 'root'}"
                groups.setdefault(fname, []).append(node)
        node_files = {}
        for fname in sorted(groups):
            self.open(fname + ".odin", "The node types of one upstream module.")
            start = len(self.lines)
            for node in groups[fname]:
                self.node(node)
            node_files[fname] = (self.lines, self.spans[self.file])
            self.close()
        # ---- traits
        self.open("gen_traits.odin", "One table per builder trait, implemented once and shared by every implementor.")
        for key in sorted(m.traits, key=lambda k: m.traits[k].get("odin", "")):
            t = m.traits[key]
            ops = sorted([i for i in t["ops"] if bound(i)], key=lambda i: i["name"])
            if "odin" not in t or not (ops or t["name"] == "Styled"):
                continue
            T = t["odin"]
            low = t["low"]
            self.add(f"// {T} is {t['path']}.", f"{T} :: struct($T: typeid) {{")
            extras = []
            if t["name"] == "Styled":
                extras.append(("style", "proc(e: T, flags: ..Style_Flag) -> T", "rt_style"))
            if t["name"] == "ParentElement":
                extras.append(("text", "proc(e: T, s: string) -> T", "rt_parent_text"))
                # child_view embeds a view: the parent's tape does not change when the child is
                # described again, so the parent stays retained.
                extras.append(("child_view", "proc(e: T, v: View) -> T", "rt_child_view"))
            for name, sig, _ in extras:
                self.add(f"\t{name}: {sig},")
            for it in ops:
                ps = self.params(it, ["e: T"])
                self.item(["item", it["id"]], [f"\t{oname(it['name'])}: proc({', '.join(ps)}) -> T,"])
            self.add("}", "")
            for it in ops:
                ps = self.params(it, ["e: Any_El"])
                lines = ["@(private)", f"{low}_{it['name']} :: proc({', '.join(ps)}) -> Any_El {{"]
                if it.get("runtime_op"):  # the runtime's CHILD op, once per child
                    a = pname(it["args"][0]["name"])
                    lines += [f"\tfor c in {a} {{", "\t\tattach(e, c)", "\t}"] if it["args"][0]["desc"][0] == "list" else [f"\tattach(e, {a})"]
                else:
                    body = self.body(it)
                    lines += [f"\to := op(e, {it['op']})"] + ["\t" + x for x in body] if body else [f"\top(e, {it['op']})"]
                lines += ["\treturn e", "}"]
                self.item(["item", it["id"]], lines)
            self.add("@(private)", f"{low}_any := {T}(Any_El) {{")
            for name, _, impl in extras:
                self.add(f"\t{name} = {impl},")
            for it in ops:
                self.item(["item", it["id"]], [f"\t{oname(it['name'])} = {low}_{it['name']},"])
            self.add("}", "")
        self.close()
        # ---- kit state behind handles
        self.open("gen_state.odin", "Kit state types: handles to entities the library keeps (PROTOCOLS.md section 5).")
        for key in sorted(m.states, key=lambda k: m.states[k].get("odin", "")):
            if "odin" in m.states[key]:
                self.state(m.states[key])
        self.close()
        # ---- enums, records, Into sets, handles, tuples, event decoders
        self.open("gen_types.odin", "Enums, records, Into sets, handle types and event payloads.")
        self.add('import "core:time"', "", "@(private)", "_gen_time :: time.Duration", "")
        for rt in sorted(m.enums, key=lambda k: m.enums[k]["odin"]):
            e = m.enums[rt]
            self.item(["enum", rt], [f"// {e['odin']} is {rt}.", f"{e['odin']} :: enum u16 {{"] +
                      [f"\t{oname(ada(v['name']))} = {v['num']}," for v in e["variants"]] + ["}", ""])
        for rt in sorted(m.denums, key=lambda k: m.denums[k]["odin"]):
            self.denum(rt, m.denums[rt])
        for rt in sorted(m.records, key=lambda k: m.records[k]["odin"]):
            self.record(rt, m.records[rt])
        for rt in sorted(m.intos, key=lambda k: m.intos[k].get("odin", "")):
            if "odin" in m.intos[rt]:
                self.into(rt, m.intos[rt])
        reg = []
        for key in sorted(m.shapes, key=lambda k: m.shapes[k]["num"]):
            sh = m.shapes[key]
            if sh["builtin"]:
                continue
            ret = {"bool": "bool", "str": "string"}.get(sh["ret"], "nil")  # str: values family (13.12)
            if len(sh["args"]) == 1:
                reg.append((key, f"\tregister_shape({sh['num']}, {self.otype(sh['args'][0], True)}, {ret}) // ({', '.join(sh['rust'])})"))
                continue
            S = f"Event_{sh['num']}"
            lines = [f"// {S}: the payload of handlers of shape {sh['num']}: ({', '.join(sh['rust'])}).", f"{S} :: struct {{"]
            lines += [f"\ta{n}: {self.otype(a, True)}," for n, a in enumerate(sh["args"])] + ["}", ""]
            self.item(["shape", key], lines)
            reg.append((key, f"\tregister_shape({sh['num']}, {S}, {ret})"))
        self.add("// The payload and return type of every generated handler shape, for the runtime's reflection.",
                 "@(init, private)", 'gen_shapes :: proc "contextless" () {')
        for key, line in reg:
            self.item(["shape", key], [line])
        self.add("}", "")
        for name, ts in sorted(self.tuples.items()):
            self.add(f"{name} :: struct {{")
            self.add(*[f"\tv{n}: {t}," for n, t in enumerate(ts)])
            self.add("}", "")
        runtime_types = set(m.ov.get("runtime", {}).get("odin_types", []))
        for name, rt in sorted(self.handles.items()):
            if name not in runtime_types:
                self.add(f"// {name} is a handle to {rt}, kept by the library.", f"{name} :: distinct Handle", "")
        self.close()
        # ---- style tokens, palette, theme
        self.open("gen_style.odin", "Style tokens (every nullary Styled and StyledExt method), palette and theme colours.")
        self.add("// Style_Flag: every nullary method of gpui's Styled trait and of the kit's style-only traits",
                 "// (StyledExt: Font_Bold, H_Flex, ...), by upstream's name.", "Style_Flag :: enum u16 {")
        for it in sorted(m.tokens, key=lambda i: i["op"]):
            if bound(it):
                self.item(["item", it["id"]], [f"\t{ada(it['name'])} = {it['op']},"])
        self.add("}", "", "// Palette: the kit's colour functions without arguments, by upstream's name.", "Palette :: enum u16 {")
        for it in sorted(m.palette, key=lambda i: i["op"]):
            if bound(it):
                self.item(["item", it["id"]], [f"\t{ada(it['name'])} = {0x8000 + it['op']},"])
        self.add("}", "", "// Theme_Color: the colour fields of the kit's theme, resolved by the library when it decodes.",
                 "Theme_Color :: enum u16 {")
        for name, n in sorted(m.theme_nums.items(), key=lambda kv: kv[1]):
            self.add(f"\t{ada(name)} = {n},")
        self.add("}")
        self.close()
        gk_app.odin_emit(self)  # the app family's ambient calls (PROTOCOLS.md section 11.5)
        gk_editor.odin_files(self)  # the editor host's element procedure (PROTOCOLS.md 9.30)
        # Parts of a described plot (docs/PROTOCOLS.md section 12): gk.plot(parts..) takes any of them.
        parts = sorted(n["odin"] for n in m.nodes.values() if n.get("paint") and n["paint"]["status"] == "bridged"
                       and any(bound(i) for i in n["ctors"]))
        if parts:
            # The binding's own parts (rt_data.odin; nodes PLOT_PATH and PLOT_QUAD, PROTOCOLS.md 12.17).
            parts = sorted(parts + list(PLOT_OWN_PARTS))
            self.open("gen_plot.odin", "The parts of a described plot: every value type that paints itself.")
            self.item(["plot", "parts"], ["// Plot_Part is a value gk.plot paints, in the order given.", "Plot_Part :: union #no_nil {"] +
                      [f"\t{p}," for p in parts] + ["}", "", "@(private)", "put_plot_part :: proc(o: ^Tape, p: Plot_Part) {",
                      "\tswitch x in p {"] + [x for p in parts for x in (f"\tcase {p}:", "\t\tput_u32(o, take_value(x.nd))")] +
                      ["\t}", "}", ""])
            self.close()
        import gk_items  # noqa: PLC0415
        gk_items.odin_emit(self)  # gk.items, after every builder that takes one was written (PROTOCOLS.md 9.41)
        self.files["gen_support.odin"] = SUPPORT.replace("OP_TEXT_N", str(OP_TEXT))
        os.makedirs(self.out, exist_ok=True)
        for f in os.listdir(self.out):
            if f.startswith("gen_") and f.endswith(".odin") and f not in self.files:
                os.remove(os.path.join(self.out, f))
        for name, text in self.files.items():
            open(os.path.join(self.out, name), "w").write(text)
        return self.spans

    def state(self, st):
        self.in_call = True  # a state's or object's call ops: values travel as tapes of their own
        try:
            self.state_body(st)
        finally:
            self.in_call = False

    def state_body(self, st):
        m = self.m
        ok = lambda i: i["status"] == "bridged"  # noqa: E731
        S = st["odin"]
        low = S.lower()
        reads = sorted([i for i in st["reads"] if ok(i)], key=lambda i: i["name"])
        writes = sorted([i for i in st["writes"] if ok(i)], key=lambda i: i["name"])
        calls = sorted([i for i in st.get("calls", []) if ok(i)], key=lambda i: i["name"])
        builders = sorted([i for i in st["builders"] if ok(i)], key=lambda i: i["name"])
        req = "\t\treq := make(Tape, 0, 32, context.temp_allocator)"
        names = {i["name"] for i in reads + writes + calls}
        # try_NAME: the read for a handler the component may call from inside its own update
        # (ok is false while the state is busy), for the reads overrides.toml names in
        # [state] try_reads. Not for every read: each is one more procedure in every app's
        # build (151 of them made the edit-loop rebuild measurably slower).
        want = set(m.ov.get("state", {}).get("try_reads", []))
        tries = [i for i in reads if i["name"] in want and "try_" + i["name"] not in names]
        obj = st.get("obj", False)
        get = "obj_get" if obj else "state_get"
        what = ("a library object the library keeps (PROTOCOLS.md section 13): a temporary handle when a read, a call or an "
                "event hands it out (gk.retain keeps it), a kept one from its constructor" if obj else "an entity the library keeps")
        if obj:
            self.add("@(init, private)", f"reg_{low} :: proc \"contextless\" () {{", f"\tregister_obj(typeid_of({S}), &{low}_vt)", "}", "")
            self.globals_statics(st)
        self.add(f"// {S} is a handle to {st['path']}, {what}.", f"{S} :: struct {{",
                 "\tusing state: State,", f"\tusing vt: ^{S}_VT,", "}", "", f"{S}_VT :: struct {{")
        for it in reads:
            self.item(["item", it["id"]], [f"\t{sname(it['name'])}: proc({', '.join(self.params(it, ['s: ' + S, 'cx: ^Cx']) + ['loc := #caller_location'])}) -> {self.otype(it['ret'], True)},"])
        for it in tries:
            self.item(["item", it["id"]], [f"\ttry_{it['name']}: proc({', '.join(self.params(it, ['s: ' + S, 'cx: ^Cx']) + ['loc := #caller_location'])}) -> ({self.otype(it['ret'], True)}, bool),"])
        for it in writes:
            self.item(["item", it["id"]], [f"\t{sname(it['name'])}: proc({', '.join(self.params(it, ['s: ' + S, 'cx: ^Cx']) + ['loc := #caller_location'])}),"])
        for it in calls:
            self.item(["item", it["id"]], [f"\t{sname(it['name'])}: proc({', '.join(self.params(it, ['s: ' + S, 'cx: ^Cx']) + ['loc := #caller_location'])}) -> {self.otype(it['ret'], True)},"])
        for ev in st["events"]:
            ev["odin"] = "on_" + snake(ev["name"])
            if ev["odin"] not in names:
                self.item(["item", ev["id"]], [f"\t{ev['odin']}: proc(s: {S}, cx: ^Cx, h: Handler, loc := #caller_location) -> Subscription,"])
        self.add("}", "", "@(private)", f"{low}_vt := {S}_VT {{")
        for it in reads:
            R = self.otype(it["ret"], True)
            lines = [f"\t{sname(it['name'])} = proc({', '.join(self.params(it, ['s: ' + S, 'cx: ^Cx']) + ['loc := #caller_location'])}) -> (v: {R}) {{", req,
                     "\t\to := &req", f"\t\tput_op(o, {it['op']})", "\t\tput_u64(o, s.h)"]
            lines += ["\t\t" + x for x in self.body(it)]
            lines += [f"\t\tr := {get}(s.h, cx, req[:], loc)", "\t\trd_into(&r, &v)", "\t\treturn", "\t},"]
            self.item(["item", it["id"]], lines)
        for it in tries:
            R = self.otype(it["ret"], True)
            lines = [f"\ttry_{it['name']} = proc({', '.join(self.params(it, ['s: ' + S, 'cx: ^Cx']) + ['loc := #caller_location'])}) -> (v: {R}, ok: bool) {{", req,
                     "\t\to := &req", f"\t\tput_op(o, {it['op']})", "\t\tput_u64(o, s.h)"]
            lines += ["\t\t" + x for x in self.body(it)]
            lines += ["\t\tr := state_try(s.h, cx, req[:], loc) or_return", "\t\trd_into(&r, &v)", "\t\treturn v, true", "\t},"]
            self.item(["item", it["id"]], lines)
        for it in calls:
            R = self.otype(it["ret"], True)
            lines = [f"\t{sname(it['name'])} = proc({', '.join(self.params(it, ['s: ' + S, 'cx: ^Cx']) + ['loc := #caller_location'])}) -> (v: {R}) {{", req,
                     "\t\to := &req", f"\t\tput_op(o, {it['op']})", "\t\tput_u64(o, s.h)"]
            lines += ["\t\t" + x for x in self.body(it)]
            lines += ["\t\tr := state_call(s.h, cx, req[:], loc)", "\t\trd_into(&r, &v)", "\t\treturn", "\t},"]
            self.item(["item", it["id"]], lines)
        for it in writes:
            lines = [f"\t{sname(it['name'])} = proc({', '.join(self.params(it, ['s: ' + S, 'cx: ^Cx']) + ['loc := #caller_location'])}) {{", req,
                     "\t\to := &req", f"\t\tput_op(o, {it['op']})", "\t\tput_u64(o, s.h)"]
            lines += ["\t\t" + x for x in self.body(it)] + ["\t\tstate_set(cx, req[:], loc)", "\t},"]
            self.item(["item", it["id"]], lines)
        for ev in st["events"]:
            if ev["odin"] in names:
                continue
            # A Subscription, not a bare Handle: gk.release on it also frees the kept handler.
            self.item(["item", ev["id"]], [
                f"\t{ev['odin']} = proc(s: {S}, cx: ^Cx, h: Handler, loc := #caller_location) -> Subscription {{",
                f"\t\tslot, generation := keep_handler(cx, h, {m.shapes[ev['shape']]['num']}, loc)", req, "\t\to := &req",
                f"\t\tput_op(o, {ev['op']})", "\t\tput_u64(o, s.h)", "\t\tput_u32(o, slot)", "\t\tput_u32(o, generation)",
                "\t\tr := state_get(s.h, cx, req[:], loc)", "\t\treturn {rd_u64(&r), slot}", "\t},"])
        self.add("}", "")
        B = S + "_Builder" if builders else S
        if builders:
            self.add(f"// {B} is the chain of {st['name']}'s `self -> Self` methods; build makes the entity, in one crossing.",
                     f"{B} :: struct {{", f"\tusing vt: ^{B}_VT,", "\tcx:       ^Cx,", "\treq:      ^Tape,", "\tcount_at: int,", "}", "",
                     f"{B}_VT :: struct {{")
            for it in builders:
                self.item(["item", it["id"]], [f"\t{oname(it['name'])}: proc({', '.join(self.params(it, ['b: ' + B]))}) -> {B},"
                                               + gk_items.vt_note(self, it)])
            self.add(f"\tbuild: proc(b: {B}) -> {S},", "}", "", "@(private)", f"{low}_builder_vt := {B}_VT {{")
            for it in builders:
                lines = [f"\t{oname(it['name'])} = proc({', '.join(self.params(it, ['b: ' + B]))}) -> {B} {{", "\t\to := b.req",
                         f"\t\tput_op(o, {it['op']})"] + ["\t\t" + x for x in self.body(it)]
                lines += ["\t\to[b.count_at] += 1", "\t\treturn b", "\t},"]
                self.item(["item", it["id"]], lines)
            self.add(f"\tbuild = proc(b: {B}) -> {S} {{", f"\t\treturn {{state = {{h = state_make(b.cx, b.req[:])}}, vt = &{low}_vt}}", "\t},", "}", "")
        for it in sorted([i for i in st["ctors"] if ok(i)], key=lambda i: i["odin"]):
            ps = ["cx: ^Cx"] + self.params(it) + ["loc := #caller_location"]
            lines = [f"{it['odin']} :: proc({', '.join(ps)}) -> {B} {{", "\treq := new(Tape, context.temp_allocator)",
                     "\treq^ = make(Tape, 0, 64, context.temp_allocator)", "\to := req", f"\tput_op(o, {it['op']})"]
            lines += ["\t" + x for x in self.body(it)] + ["\tput_u16(o, 0) // how many builder ops follow (at most 255 are counted here)"]
            if builders:
                lines += [f"\treturn {{vt = &{low}_builder_vt, cx = cx, req = req, count_at = len(req) - 2}}"]
            else:
                lines += [f"\treturn {{state = {{h = state_make(cx, req[:], loc)}}, vt = &{low}_vt}}"]
            lines += ["}", ""]
            self.item(["item", it["id"]], lines)

    def globals_statics(self, st):
        """A library object's global accessor (`Theme::global(cx)`: the handle of the kit global,
        never temporary) and its static functions, as procedures of the package."""
        S = st["odin"]
        for it in sorted([i for i in st["globals"] + st["statics"] if i["status"] == "bridged"], key=lambda i: i["odin"]):
            ps = ["cx: ^Cx"] + self.params(it) + ["loc := #caller_location"]
            head = ["\treq := make(Tape, 0, 32, context.temp_allocator)", "\to := &req", f"\tput_op(o, {it['op']})"]
            head += ["\t" + x for x in self.body(it)]
            if it["kind"] == "obj-global":
                lines = [f"{it['odin']} :: proc({', '.join(ps)}) -> {S} {{"] + head + [
                    "\tr := obj_get(0, cx, req[:], loc)", f"\treturn {{state = {{h = rd_u64(&r)}}, vt = &{S.lower()}_vt}}", "}", ""]
            elif it["kind"] == "obj-scall":
                R = self.otype(it["ret"], True)
                lines = [f"{it['odin']} :: proc({', '.join(ps)}) -> (v: {R}) {{"] + head + [
                    "\tr := state_call(0, cx, req[:], loc)", "\trd_into(&r, &v)", "\treturn", "}", ""]
            else:
                lines = [f"{it['odin']} :: proc({', '.join(ps)}) {{"] + head + ["\tstate_set(cx, req[:], loc)", "}", ""]
            self.item(["item", it["id"]], lines)

    def denum(self, rt, e):
        """An enum with data. Built by the app only: a union of one enum for the variants without
        data and one struct per variant with data. Read from the wire (an event): the form the
        runtime's reflection reads, a union of one struct per variant in wire order."""
        E = e["odin"]
        lines = [f"// {E} is {rt}."]
        members, puts = [], []
        fld = lambda v, f: oname(f["name"]) if v["shape"] == "struct" else "v" + f["name"]  # noqa: E731

        def decl(v, f, t):
            # A tuple variant whose one field is a record: the record's fields are the variant's
            # through `using` (`e.row` for ListEvent::Select(IndexPath); `e.v0.row` still works).
            one = v["shape"] not in ("struct", "unit") and len(v["fields"]) == 1 and f["desc"][0] == "rec"
            return f"\t{'using ' if one else ''}{fld(v, f)}: {t},"
        if e["out"]:
            byn = {v["num"]: v for v in e["variants"]}
            for n in range(max(byn) + 1 if byn else 0):
                v = byn.get(n)
                V = f"{E}_{ada(v['name'])}" if v else f"{E}_Reserved_{n}"
                fields = v["fields"] if v and v["ok"] else []
                lines += [f"{V} :: struct {{"] + [decl(v, f, self.otype(f['desc'], not e['in'])) for f in fields] + ["}"]
                members.append(V)
                if v and v["ok"]:
                    v["odin"] = V
                    puts.append((V, [f"put_u16(o, {n})"] + [x for f in fields for x in self.put(f["desc"], f"x.{fld(v, f)}")]))
            for v in e["variants"]:
                if v["ok"] and v["shape"] == "unit":
                    v["unit_odin"] = f"{E}_{ada(v['name'])}{{}}"
        else:
            units = [v for v in e["variants"] if v["ok"] and v["shape"] == "unit"]
            if units:
                lines += [f"{E}_Kind :: enum u16 {{"] + [f"\t{oname(ada(v['name']))} = {v['num']}," for v in units] + ["}"]
                members.append(f"{E}_Kind")
                puts.append((f"{E}_Kind", ["put_u16(o, u16(x))"]))
            for v in e["variants"]:
                if v["ok"] and v["shape"] != "unit":
                    V = f"{E}_{ada(v['name'])}"
                    v["odin"] = V
                    lines += [f"{V} :: struct {{"] + [decl(v, f, self.otype(f['desc'])) for f in v["fields"]] + ["}"]
                    members.append(V)
                    puts.append((V, [f"put_u16(o, {v['num']})"] + [x for f in v["fields"] for x in self.put(f["desc"], f"x.{fld(v, f)}")]))
        gk_editor.odin_denum(self, e, members, puts, lines)  # a value the library holds (PROTOCOLS.md 9.30)
        e["members"] = members
        one = len(members) == 1
        if one and e["out"] and not members[0].endswith("_Kind"):
            # One variant still travels with its u16 variant number in front, and the runtime's
            # reflection reads a one-member union as a Maybe: a struct with the number, the
            # variant's fields reachable through `using`. As a bare alias of the variant the
            # number was read as the first field (ColorPickerEvent::Change arrived as nil; found
            # by the generated shape test).
            lines += [f"{E} :: struct {{", "\tvariant:     u16,", f"\tusing value: {members[0]},", "}", ""]
        else:
            lines += [f"{E} :: {members[0]}", ""] if one else [f"{E} :: union #no_nil {{"] + [f"\t{x}," for x in members] + ["}", ""]
        if e["in"]:
            lines += ["@(private)", f"put_{E} :: proc(o: ^Tape, v: {E}) {{",
                      "\tx := v" if one else ("\t#partial switch x in v {" if e["out"] else "\tswitch x in v {")]
            for V, body in puts:
                lines += [f"\tcase {V}:"] * (not one) + ["\t\t" + b for b in body]
            if e["out"] and not one:
                lines += ["\tcase:", "\t\tput_u16(o, 0xffff)"]
            lines += ["\t}"] * (not one) + ["}", ""]
        self.item(["denum", rt], lines)

    def record(self, rt, rc):
        R = rc["odin"]
        fname = lambda f: ("v" + f["name"]) if rc["tuple"] else oname(f["name"])  # noqa: E731
        lines = [f"// {R} is {rt}." + ("" if rc["complete"] else " Only the fields the binding can carry."), f"{R} :: struct {{"]
        lines += [f"\t{fname(f)}: {self.otype(f['desc'], not rc['in'])}," for f in rc["fields"]] + ["}", ""]
        if rc["in"]:
            lines += ["@(private)", f"put_{R} :: proc(o: ^Tape, v: {R}) {{"]
            for f in rc["fields"]:
                lines += ["\t" + s for s in self.put(f["desc"], f"v.{fname(f)}")]
            lines += ["}", ""]
        if rc.get("short_odin"):
            U, f = rc["short_odin"], oname(rc["shorthand"])
            lines += [f"// {U['one']} is a {R} where a call takes one: the {f} alone (the other fields 0) or the record",
                      f"// (PROTOCOLS.md 11.36). {U['opt']} is an option of it (nil: none), {U['list']} a list of",
                      f"// either (nil: empty).",
                      f"{U['one']} :: union #no_nil {{int, {R}}}", f"{U['opt']} :: union {{int, {R}}}",
                      f"{U['list']} :: union {{[]int, []{R}}}", ""]
        self.item(["rec", rt], lines)

    def into(self, rt, s):
        """`impl Into<T>`: a union of the members; a member that is itself a union is spread."""
        I = s["odin"]
        cases, seen = [], set()
        for n, mem in enumerate(s["members"]):
            d = mem["desc"]
            t = self.otype(d)
            spread = self.m.denums[d[1]]["members"] if d[0] == "denum" else [t]
            for u in spread:
                if u not in seen:
                    seen.add(u)
                    cases.append((u, n, d))
        one = len(cases) == 1
        lines = [f"// {I} is what `impl Into<{rt}>` accepts."]
        lines += [f"{I} :: {cases[0][0]}"] if one else [f"{I} :: union #no_nil {{"] + [f"\t{u}," for u, _, _ in cases] + ["}"]
        lines += ["", "@(private)", f"put_{I} :: proc(o: ^Tape, v: {I}) {{", "\tx := v" if one else "\tswitch x in v {"]
        for u, n, d in cases:
            lines += [f"\tcase {u}:"] * (not one) + [f"\t\tput_u8(o, {n})"] + ["\t\t" + x for x in self.put(d, "x")]
        lines += ["\t}"] * (not one) + ["}", ""]
        self.item(["into", rt], lines)

    def node(self, node):
        m = self.m
        bound = lambda i: i["status"] in ("bound", "bridged")  # noqa: E731
        T = node["odin"]
        low = T.lower()
        base = "using el: Element" if node["element"] else "using nd: Value"
        self.add(f"// {T} is {node['path']}.", f"{T} :: struct {{", f"\t{base},", f"\tusing vt: ^{T}_VT,", "}", "")
        ops = sorted([i for i in node["ops"] if bound(i)], key=lambda i: i["name"])
        opnames = {i["name"] for i in ops}
        convs, cseen = [], set()
        for i in sorted([i for i in node.get("converts", []) if bound(i)], key=lambda i: (i["trait"] or "", i["name"])):
            if i["name"] not in opnames and i["name"] not in cseen:  # an inherent method shadows a trait's
                cseen.add(i["name"])
                convs.append(i)
        own = {oname(i["name"]) for i in ops} | {oname(i["name"]) for i in convs}
        el = "e.el" if node["element"] else "vel(e.nd)"
        vt = [f"{T}_VT :: struct {{"]
        init = ["@(private)", f"{low}_vt := {T}_VT {{"]
        seen = set(own) | {"el", "nd", "vt", "node", "serial"}
        for tk in node["tables"]:
            t = next(t for t in m.traits.values() if t["key"] == tk)
            if "odin" not in t:
                continue
            tops = [i for i in t["ops"] if bound(i)]
            names = [oname(i["name"]) for i in tops]
            if t["name"] == "Styled":
                names.append("style")
            if t["name"] == "ParentElement" and node["element"]:
                names += ["text", "child_view"]
            tl = t["low"]
            if not names:
                continue
            if not (set(names) & seen):
                vt.append(f"\tusing t_{tl}: ^{t['odin']}({T}),")
                init.append(f"\tt_{tl} = cast(^{t['odin']}({T}))&{tl}_any,")
                seen |= set(names)
                continue
            # a name is taken (an inherent method shadows the trait's): the rest one by one
            for i in tops:
                n = oname(i["name"])
                if n in seen:
                    continue
                seen.add(n)
                sig = f"proc({', '.join(self.params(i, ['e: ' + T]))}) -> {T}"
                vt.append(f"\t{n}: {sig},")
                init.append(f"\t{n} = transmute({sig}){tl}_{i['name']},")
            if t["name"] == "Styled" and "style" not in seen:
                seen.add("style")
                sig = f"proc(e: {T}, flags: ..Style_Flag) -> {T}"
                vt.append(f"\tstyle: {sig},")
                init.append(f"\tstyle = transmute({sig})rt_style,")
        self.add(*vt)
        for it in ops:
            self.item(["item", it["id"]], [f"\t{oname(it['name'])}: proc({', '.join(self.params(it, ['e: ' + T]))}) -> {T},"
                                           + gk_items.vt_note(self, it)])
        for it in convs:
            it["emitted"] = True
            U = m.nodes[it["node"]]["odin"]
            self.item(["item", it["id"]], [f"\t{oname(it['name'])}: proc({', '.join(self.params(it, ['e: ' + T]))}) -> {U},"])
        self.add("}", "")
        # constructors
        for it in sorted([i for i in node["ctors"] if bound(i) and i["kind"] != "convert"], key=lambda i: i["odin"]):
            ps = self.params(it)
            variadic = bool(it["args"]) and it["args"][-1]["desc"][0] == "list" and it["args"][-1]["desc"][1] == ["child"]
            if variadic:
                ps[-1] = ps[-1].replace(": []", ": ..")
            if node["styled"] and not variadic:
                ps.append("flags: ..Style_Flag")
            ps.append("loc := #caller_location")
            lines = ["@(private)"] * bool(it.get("handed"))  # an item procedure's handed element (PROTOCOLS.md 9.41)
            lines += [f"{it['odin']} :: proc({', '.join(ps)}) -> {T} {{", f"\te := {T}{{{'new_node' if node['element'] else 'new_value'}({it['op']}, loc), &{low}_vt}}"]
            body = self.body(it)
            if body:
                lines += ["\to := node_args()"] + ["\t" + s for s in body]
            if node["styled"] and not variadic:
                lines.append(f"\ttokens({el}, flags)")
            lines += ["\treturn e", "}", ""]
            self.item(["item", it["id"]], lines)
        self.add(*init)
        for it in ops:
            body = self.body(it)
            lines = [f"\t{oname(it['name'])} = proc({', '.join(self.params(it, ['e: ' + T]))}) -> {T} {{"]
            lines += [f"\t\to := op({el}, {it['op']})"] + ["\t\t" + s for s in body] if body else [f"\t\top({el}, {it['op']})"]
            lines += ["\t\treturn e", "\t},"]
            self.item(["item", it["id"]], lines)
        for it in convs:
            target = m.nodes[it["node"]]
            U = target["odin"]
            lines = [f"\t{oname(it['name'])} = proc({', '.join(self.params(it, ['e: ' + T]))}) -> {U} {{",
                     f"\t\tsrc := take({el}, receiver = true)",
                     f"\t\tn := {U}{{{'new_node' if target['element'] else 'new_value'}({it['op']}), &{U.lower()}_vt}}",
                     "\t\to := node_args()", "\t\tput_u32(o, src)"]
            lines += ["\t\t" + s for s in self.body(it)] + ["\t\treturn n", "\t},"]
            self.item(["item", it["id"]], lines)
        self.add("}", "")
