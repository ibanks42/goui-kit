def gensample(m, go, path):
    """core/tests/go/gensample/main.go: the sample by generation. Returns (calls, skipped)."""
    sm = GoSample(m, go)
    body = []
    calls = skipped = 0
    fns = []
    for key in sorted(m.nodes):
        node = m.nodes[key]
        meths = sm.methods(node) if "go" in node else {}
        base = sm.make(node)
        if base is None:
            skipped += sum(1 for i in node["ctors"] + node["ops"] if bound(i))
            continue
        fn = "s" + camel(node["fn"])
        fns.append(fn)
        body.append(f"func {fn}() {{")
        for it in sorted(node["ctors"], key=lambda i: i["id"]):
            if not bound(it) or (it["kind"] == "convert" and not it.get("emitted")) or it.get("handed"):
                continue
            if it["kind"] == "convert":
                c = sm.conv(it, 1)
                if c is None:
                    skipped += 1
                    continue
                body.append(f"\t_ = {c}")
            else:
                a = sm.args(it, 0, sm.variadic_ctor(node, it)) if sm.ctor_ok(it) else None
                if a is None:
                    skipped += 1
                    continue
                body.append(f"\t_ = gk.{it['go']}({a})")
            calls += 1
        body.append(f"\te := {base}")
        for it in sorted(node["ops"], key=lambda i: i["name"]):
            if not bound(it):
                continue
            name = camel(it["name"])
            a = sm.args(it, 0, sm.variadic_op(it)) if meths.get(name, (None, None))[1] is it else None
            if a is None:
                skipped += 1
                continue
            body.append(f"\te = e.{name}({a})")
            calls += 1
        for name, (kind, it) in meths.items():
            if kind != "trait":
                continue
            a = sm.args(it, 0, sm.variadic_op(it))
            if a is None:
                continue
            body.append(f"\te = e.{name}({a})")
            calls += 1
        if node["styled"] and meths.get("Style", (None,))[0] == "style":
            toks = [i for i in m.tokens if bound(i) and i["id"] in sm.tok]
            if toks:
                pick = [toks[(len(body) * 7 + j * 131) % len(toks)] for j in range(3)]
                body.append(f"\te = e.Style({', '.join('s.' + sm.tok[i['id']] for i in pick)})")
        body += ["\t_ = e", "}", ""]
    o = [HEAD, "", "// The sample by generation in Go (gen/gk_tests_go.py gensample): every",
         "// constructor and builder the Go package generated, once. Run offscreen against the real",
         "// runtime by gates/go-gensample.sh: every generated function exists and writes a tape the",
         "// runtime accepts.", "package main", ""]
    rest = ["type App struct {", "\troot gk.View", "\truns int", "}", ""]
    if "action" in sm.uses:
        rest += ["// sampleAct is the action every builder that takes one gets (made when the app starts).",
                 "var sampleAct gk.Action", ""]
    rest += sm.helpers("sampleRow") + body
    rest += ["func (a *App) rootView(cx *gk.Cx) gk.Element {"] + [f"\t{f}()" for f in fns]
    rest += ["\ta.runs++", f'\tfmt.Printf("gensample: {calls} calls in {len(fns)} node types, run %d\\n", a.runs)',
             '\treturn gk.Div(s.SizeFull).Text("gensample")', "}", "",
             "func main() {", "\ta := &App{}", '\tgk.RunHeadless("frame\\nframe\\n", func(cx *gk.Cx) {']
    if "action" in sm.uses:
        rest.append('\t\tsampleAct = gk.NewAction(cx, "gensample.sample")')
    rest += ["\t\ta.root = gk.NewView(nil, a.rootView)", '\t\tgk.OpenWindow(cx, "gensample", 640, 480, a.root)', "\t})",
             '\tfmt.Printf("gensample: done runs=%d\\n", a.runs)', "}"]
    text = "\n".join(rest)
    write(path, o + imports(text, ["fmt"]) + rest)
    return calls, skipped


