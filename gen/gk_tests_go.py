def gen_test(m, go, path, skip):
    """core/tests/go/gen/main.go: modes shapes and states (gen/gk_tests.py)."""
    saved = (dict(go.names), list(go.collisions), dict(go.tuples), dict(go.handles), dict(go.oneofs), set(go.need_readers))
    sh = gk_tests.shapes(m)
    enc = Enc(m, go)
    sa = StateArgs(m, go, "")
    st = go_states(m, go, sa, set(skip.get("calls", [])))
    # shapes
    hs, runs, n, skips = [], [], 0, []
    for s in sh:
        if "skip" in s:
            runs.append(f"\t// shape {s['num']} ({', '.join(s['rust'])}): no sample ({s['skip']})")
            skips.append(s)
            continue
        shape = next(x for x in m.shapes.values() if x["num"] == s["num"])
        why = None
        if not shape.get("go_ok", True):
            why = f"not in Go ({shape.get('go_why')})"
        else:
            try:
                ev, ret = go.event_type(shape), go.ret_type(shape)
                args = go.shape_args(shape)
                if not all(enc.readable(a) for a in args):
                    why = "the Go package cannot read its payload"
            except Unsup as e:
                why = f"not in Go ({e})"
        if why:
            runs.append(f"\t// shape {s['num']} ({', '.join(s['rust'])}): {why}")
            skips.append({**s, "skip": why})
            continue
        body = []
        if len(args) == 1:
            body = enc.enc(args[0], "e")
        elif args:
            body = [x for i, a in enumerate(args) for x in enc.enc(a, f"e.A{i}")]
        back = {"bool": "\n\treturn true", "string": '\n\treturn "s"'}.get(ret, "")
        hs.append(f"// shape {s['num']}: ({', '.join(s['rust'])}){' -> bool' if s['ret'] == 'bool' else ''}")
        hs.append(f"func h{s['num']}(cx *gk.Cx{', e ' + qualify(ev) if ev else ''}){' ' + ret if ret else ''} {{")
        if ev:
            hs += ["\tw := &wbuf{}"] + ["\t" + x for x in body] + ["\tapp.gotBytes(w.b)" + back, "}", ""]
        else:
            hs += ["\tapp.gotBytes(nil)" + back, "}", ""]
        n += 1
        want_ret = {"bool": "{0x01}", "str": "{0x01, 0x00, 0x00, 0x00, 0x73}"}.get(s["ret"], "{}")
        runs.append(f"\ta.tryShape(cx, {s['num']}, \"({', '.join(s['rust'])})\", h{s['num']}, []byte{gk_tests.lit(s['bytes'])}, "
                    f"{'true' if s['typed'] else 'false'}, []byte{want_ret})")
    skipped_nums = {x["num"] for x in skips}
    typed = sum(1 for s in sh if s.get("typed") and s["num"] not in skipped_nums)
    # states
    mk, rel, made, any_ev, notread = [], [], 0, {}, []
    for s in st:
        if "skip" in s:
            mk.append(f"\t// {s['stem']}: not made here: {s['skip']}")
            continue
        made += 1
        F = f"a.{s['field']}"
        mk.append(f"\t{F} = {s['make']}")
        for name, args in s["reads"]:
            if args == "stop":
                mk.append(f"\t// {name}: skipped: the Go package does not read its result yet (its reader stops)")
                notread.append(f"{s['go']}.{name}")
                continue
            mk.append(f"\t_ = {F}.{name}(cx{', ' + args if args else ''})")
        for name, args in s["calls"]:
            if args == "stop":
                mk.append(f"\t// {name}: skipped: the Go package does not read its result yet (its reader stops)")
                notread.append(f"{s['go']}.{name}")
                continue
            if args is None:
                mk.append(f"\t// {name}: skipped (api/overrides.toml [tests] calls)")
                continue
            mk.append(f"\t_ = {F}.{name}(cx{', ' + args if args else ''})")
        for name, args in s["writes"]:
            if args is None:
                mk.append(f"\t// {name}: skipped (api/overrides.toml [tests] calls)")
                continue
            mk.append(f"\t{F}.{name}(cx{', ' + args if args else ''})")
        for name, shp in s["events"]:
            num = shp["num"]
            if num not in any_ev:
                ev, ret = go.event_type(shp), go.ret_type(shp)
                back = {"bool": "\n\treturn false", "string": '\n\treturn ""'}.get(ret, "")
                any_ev[num] = (f"func anyEvent{num}(cx *gk.Cx{', e ' + qualify(ev) if ev else ''}){' ' + ret if ret else ''} {{\n"
                               f"\tapp.events++{back}\n}}")
            mk.append(f"\ta.subs = append(a.subs, {F}.{name}(cx, anyEvent{num}))")
        mk.append(f"\tfmt.Printf(\"states made {s['stem']} builders={s['builders']} reads={len(s['reads'])} "
                  f"writes={len(s['writes'])} calls={len(s['calls'])} events={len(s['events'])}\\n\")")
        first = next(((n, x) for n, x in s["reads"] if x is not False and x != "stop"), None)
        if first:
            name, args = first
            rel.append(f"\t_ = {F}.{name}(cx{', ' + args if args else ''})")
        rel.append(f"\tgk.Release(cx, {F})")
    o = [HEAD, "", "// The generated protocol tests in Go (gen/gk_tests.py, gen/gk_tests_go.py): every handler",
         "// shape the package registers fired once through the library, every generated state type made,",
         "// read, written, called, subscribed and released. Run by core/tests/go/run-gen.sh",
         "// (GK_PROTO=shapes | states), offscreen, with the diag library.", "package main", ""]
    rest = ["type App struct {", "\tmode   string", "\troot   gk.View", "\tclicks int", "\tgot    []byte", "\tfired  bool",
            "\tok     int", "\tfailed int", "\ttyped  int", "\tevents int", "\tsubs   []gk.Subscription"]
    rest += [f"\t{s['field']} gk.{s['go']}" for s in st if "make" in s]
    rest += ["}", "", "var app = &App{}", ""]
    if "action" in sa.uses:
        rest += ["var sampleAct gk.Action", ""]
    rest += sa.helpers("sampleRow")
    rest += GEN_RUNTIME + enc.funcs()
    rest += ["func (a *App) gotBytes(b []byte) {", "\ta.got = bytes.Clone(b)", "\ta.fired = true", "}", "",
             "func (a *App) tryShape(cx *gk.Cx, num uint16, name string, h any, payload []byte, wantTyped bool, wantRet []byte) {",
             "\ta.got, a.fired = nil, false",
             "\ttyped, ret := gk.TestFireShape(cx, h, num, payload)",
             "\tok := a.fired && bytes.Equal(a.got, payload) && bytes.Equal(ret, wantRet) && typed == wantTyped",
             '\tfmt.Printf("shape %d %s %s %s\\n", num, pick(typed, "typed", "raw"), pick(ok, "ok", "FAIL"), name)',
             "\tif ok {", "\t\ta.ok++", "\t} else {", "\t\ta.failed++",
             '\t\tfmt.Printf("  fired=%v sent=%x got=%x ret=%x want_ret=%x typed=%v want_typed=%v\\n", a.fired, payload, a.got, ret, wantRet, typed, wantTyped)',
             "\t}", "\tif typed {", "\t\ta.typed++", "\t}", "}", "",
             "func pick(c bool, a, b string) string {", "\tif c {", "\t\treturn a", "\t}", "\treturn b", "}", ""]
    rest += hs
    rest += [any_ev[k] for k in sorted(any_ev)] + [""]
    rest += ["func (a *App) runShapes(cx *gk.Cx) {"] + runs
    rest += [f'\tfmt.Printf("shapes done ok=%d failed=%d typed=%d of {n}\\n", a.ok, a.failed, a.typed)', "}", ""]
    rest += ["// makeStates: made, used and subscribed in one turn; read again and released in the next.",
             "func (a *App) makeStates(cx *gk.Cx) {"]
    if "action" in sa.uses:
        rest.append('\tsampleAct = gk.NewAction(cx, "gen.sample")')
    rest += mk + [f'\tfmt.Printf("states made all n={made}\\n")', "}", "",
                  "func (a *App) releaseStates(cx *gk.Cx) {"] + rel
    rest += ["\tfor _, sub := range a.subs {", "\t\tgk.Release(cx, sub)", "\t}",
             f'\tfmt.Printf("states released n={made} subscriptions=%d\\n", len(a.subs))', "}", "",
             "func (a *App) clicked(cx *gk.Cx, _ gk.ClickEvent) {", "\ta.clicks++", "\tswitch a.mode {", '\tcase "shapes":',
             "\t\tif a.clicks == 1 {", "\t\t\ta.runShapes(cx)", "\t\t}", '\tcase "states":', "\t\tswitch a.clicks {",
             "\t\tcase 1:", "\t\t\ta.makeStates(cx)", "\t\tcase 2:", "\t\t\ta.releaseStates(cx)", "\t\t}", "\t}", "}", "",
             "func (a *App) rootView(cx *gk.Cx) gk.Element {",
             '\treturn gk.Div(s.SizeFull).ID("all").OnClick(a.clicked).Text("gen")', "}", "",
             "func main() {", "\tapp.mode = os.Getenv(\"GK_PROTO\")",
             '\tscript := "size 320 200\\nframe\\nclick 100 100\\nframe\\nframe\\nclick 100 100\\nframe\\nframe\\nstat\\n"',
             "\tgk.RunHeadless(script, func(cx *gk.Cx) {", "\t\tapp.root = gk.NewView(nil, app.rootView)",
             '\t\tgk.OpenWindow(cx, "gen", 320, 200, app.root)', "\t})",
             '\tfmt.Printf("gen done mode=%s clicks=%d ok=%d failed=%d events=%d\\n", app.mode, app.clicks, app.ok, app.failed, app.events)',
             "}"]
    text = "\n".join(rest)
    write(path, o + imports(text, ["fmt", "bytes", "math", "reflect", "encoding/binary", "os"]) + rest)
    go.names, go.collisions, go.tuples, go.handles, go.oneofs, go.need_readers = saved
    return {"shapes": n, "shape_skips": skips, "typed": typed, "states": made, "state_skips": [s for s in st if "skip" in s],
            "notread": notread}


