"""The generated protocol tests in Go, written by `make gen` from the model and the Go names
gen/gk_go.py gave it, into core/tests/go (core/tests/go/README.md):

  core/tests/go/gensample/main.go   every Go-bound constructor and builder once (gates/go-gensample.sh)
  core/tests/go/gen/main.go         modes shapes and states (core/tests/go/run-gen.sh)
  core/tests/go/app/gen_ambient.go  every ambient call once (the app family's mode ambient)

Only what the Go package generated is called: an item gk_go left out (gen/out/go-report.md) is
counted as skipped, as an item the sample has no argument for is. The sample values are Go
expressions (GoSample). Go has no generic re-encoder, so the shapes test carries one encoder per
payload type, written here from the wire descriptors (the Rust `Wire` layout gk_tests.Bytes writes and the Go readers read).
"""
import os
import re
import shutil
import subprocess

import gk_app
import gk_tests
from gk_go import Unsup, camel
from gk_model import INT_WIRE, ada, snake, walk_desc

HEAD = "// Code generated by gen/gkgen.py (gen/gk_tests_go.py). DO NOT EDIT."
WIDTH = {"u8": 8, "i8": 8, "u16": 16, "i16": 16, "u32": 32, "i32": 32, "u64": 64, "i64": 64}
BASIC = {"bool", "string", "int", "rune", "float32", "float64", "uint8", "uint16", "uint32", "uint64",
         "int8", "int16", "int32", "int64"}


def qualify(t):
    """A Go type as gk_go writes it inside package gk -> as a test outside it writes it."""
    return re.sub(r"(?<![\w.])([A-Z]\w*)", r"gk.\1", t)


def bound(i):
    return i["status"] in ("bound", "bridged")


class GoSample:
    """Sample argument values as Go expressions, for what the Go
    package generated. `pre` prefixes the helpers it asks the file for (handlers, rows, the
    action), so two generated files can share a package."""

    def __init__(self, m, go, pre=""):
        self.m, self.go, self.pre = m, go, pre
        self.handlers = {}      # shape number -> helper name
        self.uses = set()       # "rows", "action"
        self.meths = {}         # node key -> {Go method name: (kind, item)}
        div = next((n for n in m.nodes.values() if n["name"] == "Div" and n["crate"] == "gpui"), None)
        ok = div is not None and any(self.ctor_ok(i) and i.get("stem") == "div" for i in div["ctors"])
        self.elem = "gk.Div()" if ok else None
        self.tok = {}
        seen = set()
        for it in sorted(m.tokens, key=lambda i: i["op"]):  # gk_go.Go.tokens' names
            if bound(it):
                n = camel(ada(it["name"]))
                if n in seen:
                    n += "_"
                seen.add(n)
                self.tok[it["id"]] = n

    # ------------------------------------------------------------ what Go has

    def mapped(self, it):
        return it["id"] in self.go.mapped

    def ctor_ok(self, it):
        """A constructor the Go package generated (a convert is checked on its source)."""
        return bound(it) and it["kind"] != "convert" and "go" in it and self.mapped(it)

    def methods(self, node):
        """The methods gk_go.Go.node gave the node's type: Go name -> (kind, item), in its order
        (own ops, converts, the traits'; an earlier one shadows a later one of the same name)."""
        key = id(node)
        if key in self.meths:
            return self.meths[key]
        m = self.m
        seen, out = {"node", "valueNode"}, {}
        for it in sorted([i for i in node.get("ops", []) if bound(i)], key=lambda i: i["name"]):
            name = camel(it["name"])
            if name in seen or not self.mapped(it):
                continue
            seen.add(name)
            out[name] = ("op", it)
        for it in sorted([i for i in node.get("converts", []) if bound(i)], key=lambda i: (i["trait"] or "", i["name"])):
            name = camel(it["name"])
            if name in seen or "go" not in m.nodes.get(it["node"], {}) or not self.mapped(it):
                continue
            seen.add(name)
            out[name] = ("conv", it)
        for tk in node["tables"]:
            t = next(t for t in m.traits.values() if t["key"] == tk)
            if "stem" not in t:
                continue
            if t["name"] == "Styled" and "Style" not in seen:
                seen.add("Style")
                out["Style"] = ("style", None)
            if t["name"] == "ParentElement" and node["element"]:
                seen.update(("Text", "ChildView"))
            for it in sorted([i for i in t["ops"] if bound(i)], key=lambda i: i["name"]):
                name = camel(it["name"])
                if name in seen or not self.mapped(it):
                    continue
                seen.add(name)
                out[name] = ("trait", it)
        self.meths[key] = out
        return out

    def stops(self, d, out=True, seen=None):
        """True when a reader the Go package generated for d (any variant that may arrive, every
        record field) is a stop: a type gk_go does not read yet ("cannot be read by the Go package
        yet"). Those reads are not in Go, so the test leaves them out."""
        m, k = self.m, d[0]
        seen = set() if seen is None else seen
        if k in ("rec", "denum"):
            if (k, d[1], out) in seen:
                return False
            seen.add((k, d[1], out))
            if k == "rec":
                rc = m.records[d[1]]
                fs, o = rc["fields"], not rc["in"]
            else:
                e = m.denums[d[1]]
                fs, o = [f for v in e["variants"] if v.get("ok") and "go" in v for f in v["fields"]], not e["in"]
            for f in fs:
                try:
                    self.go.rd(f["desc"], o)
                except (Unsup, KeyError):
                    return True
            return any(self.stops(f["desc"], o, seen) for f in fs)
        if k in ("ref", "from", "refmut", "rcvec", "opt", "list", "arcslice", "iter", "array", "rangeof"):
            return self.stops(d[1], out, seen)
        if k == "tuple":
            return any(self.stops(x, out, seen) for x in d[1])
        return False

    def put_ok(self, d):
        try:
            self.go.put(d, "v")
            return True
        except (Unsup, KeyError):
            return False

    def T(self, d, out=False):
        return qualify(self.go.gtype(d, out))

    # ------------------------------------------------------------ values

    def val(self, d, depth=0):
        m, k = self.m, d[0]
        if depth > 4:
            return None
        if k not in ("ref", "from", "refmut", "child", "fragment") and not self.put_ok(d):
            return None
        if k == "bool":
            return "true"
        if k == "int":
            return "3"
        if k == "leaf" and d[1] in ("click_event", "key_event", "mouse_event"):
            return None
        if k in ("f32", "f64"):
            return "1.5"
        if k == "str":
            return '"s"'
        if k == "leaf":
            return {"px": "4", "rems": "1", "color": "gk.HSLA(0.5, 0.25, 0.75, 1)", "length": "gk.Px(8)",
                    "definite_length": "gk.Px(8)", "absolute_length": "gk.Px(8)", "id": '"id"',
                    "duration": "250 * time.Millisecond", "range": "gk.Range{Lo: 1, Hi: 3}"}.get(d[1])
        if k == "enum":
            e = m.enums[d[1]]
            return f"gk.{e['variants'][0]['go']}" if e["variants"] else None
        if k == "denum":
            return self.denum(m.denums[d[1]], depth)
        if k == "rec":
            rc = m.records[d[1]]
            if rc.get("go_bad") or not rc["in"]:
                return None
            vs = [self.val(f["desc"], depth + 1) for f in rc["fields"]]
            if None in vs:
                return None
            fname = (lambda f: "V" + f["name"]) if rc["tuple"] else (lambda f: camel(f["name"]))
            return f"gk.{rc['go']}{{{', '.join(f'{fname(f)}: {v}' for f, v in zip(rc['fields'], vs))}}}"
        if k == "into":
            s = m.intos[d[1]]
            if "go" not in s:
                return self.val(s["members"][0]["desc"], depth + 1)
            for t, md in self.into_members(s):
                v = self.val(md, depth + 1)
                if v is not None:
                    return f"{t}({v})" if t in BASIC else v
            return None
        if k in ("ref", "from", "refmut"):
            return self.val(d[1], depth)
        if k == "opt":
            v = self.val(d[1], depth)
            return None if v is None else f"gk.Some[{self.T(d[1])}]({v})"
        if k == "list":
            v = self.val(d[1], depth + 1)
            return None if v is None else f"[]{self.T(d[1])}{{{v}}}"
        if k == "tuple":
            vs = [self.val(x, depth + 1) for x in d[1]]
            return None if None in vs else f"{self.T(d)}{{{', '.join(f'V{n}: {v}' for n, v in enumerate(vs))}}}"
        if k in ("child", "fragment"):
            return self.elem
        if k == "array":
            v = self.val(d[1], depth + 1)
            return None if v is None else f"[{d[2]}]{self.T(d[1])}{{{', '.join([v] * d[2])}}}"
        if k in ("node", "build", "stylefn"):
            return self.make(m.nodes[d[1]], depth + 1)
        if k in ("entity", "handle", "obj"):
            return f"{self.T(d)}{{}}"  # a zero handle: the sample's elements are never drawn
        if k == "action":
            self.uses.add("action")
            act = self.pre + "sampleAct"
            return f"gk.Act({act}, func(cx *gk.Cx, a gk.Action) {{}})" if d[1] == "listener" else act
        if k == "handler":
            return self.handler(m.shapes[d[1]])
        if k == "data":
            self.uses.add("rows")
            return f"gk.NewData({self.pre}sampleRows)"
        if k == "field":
            return {"text": '"Label"', "num": '"Value"', "opt": '"Gap"', "color": '"Color"'}[d[1]]
        if k == "format":
            nums = sum(1 for f in d[5] if f[0] in ("f32", "f64", "int"))
            row = any(f[0] == "datum" for f in d[5])
            return '"' + ("{Label} " if row else "") + ("{:.1}" if nums else "s") + '"'
        return None

    def into_members(self, s):
        """An Into set's members as gk_go's put of the set takes them: (Go type, descriptor), the
        first member of each Go type."""
        seen = set()
        for mem in s["members"]:
            md = mem["desc"]
            try:
                t = self.go.gtype(md)
                self.go.put(md, "x")
            except (Unsup, KeyError):
                continue
            if t not in seen:
                seen.add(t)
                yield t, md

    def handler(self, sh):
        """A handler of the shape that does nothing (a named function, one per shape)."""
        n = sh["num"]
        if n not in self.handlers:
            ev, ret = self.go.event_type(sh), self.go.ret_type(sh)
            name = f"{self.pre}noop{n}"
            back = {"bool": " { return false }", "string": ' { return "" }'}.get(ret, " {}")
            self.handlers[n] = (name, f"func {name}(cx *gk.Cx{', e ' + qualify(ev) if ev else ''}){' ' + ret if ret else ''}{back}")
        return self.handlers[n][0]

    def denum(self, e, depth):
        if not e["in"] or e.get("go_bad"):
            return None
        units = self.go.unit_values(e)
        for v in e["variants"]:
            if v["ok"] and v["shape"] == "unit" and "go" in v:
                return f"gk.{v['go']}" if v in units else f"gk.{v['go']}{{}}"
        for v in e["variants"]:
            if v["ok"] and "go" in v and not v.get("go_bad"):
                if not all(self.put_ok(f["desc"]) for f in v["fields"]):
                    continue
                vs = [self.val(f["desc"], depth + 1) for f in v["fields"]]
                if None in vs:
                    continue
                if self.go.embeds(v):
                    return f"gk.{v['go']}{{{vs[0]}}}"
                return f"gk.{v['go']}{{{', '.join(f'{self.go.vfield(v, f)}: {x}' for f, x in zip(v['fields'], vs))}}}"
        return None

    def args(self, it, depth=0, variadic=False):
        vs = []
        ds = [a["desc"] for a in it["args"] if a["desc"][0] != "ctx"]
        for n, d in enumerate(ds):
            if variadic and n == len(ds) - 1 and d[0] == "list":
                vs.append(self.val(d[1], depth + 1))  # one element for `...Element`
            else:
                vs.append(self.val(d, depth))
        return None if None in vs else ", ".join(vs)

    @staticmethod
    def variadic_ctor(node, it):
        return bool(it["args"]) and it["args"][-1]["desc"][0] == "list" and it["args"][-1]["desc"][1] == ["child"]

    @staticmethod
    def variadic_op(it):
        return bool(it.get("runtime_op")) and bool(it["args"]) and it["args"][0]["desc"][0] == "list"

    def conv(self, it, depth):
        """`src.Name(args)` for a convert constructor, or None."""
        src_node = self.m.nodes.get(it["from"])
        if src_node is None or "go" not in src_node:
            return None
        name = camel(it["name"])
        if self.methods(src_node).get(name, (None, None))[1] is not it:
            return None
        a = self.args(it, depth)
        if a is None:
            return None
        src = self.make(src_node, depth + 1) if depth < 4 else None
        if src is None:
            return None
        lifted = getattr(getattr(self.go, "split", None), "lifted_map", {}).get((src_node["go"], name))
        if lifted:  # a function of the later package now (gen/gk_split.py rule 4)
            return f"gk.{lifted}({src}{', ' + a if a else ''})"
        return f"{src}.{name}({a})"

    def make(self, node, depth=0):
        """An expression that constructs a node of this type, by its simplest constructor."""
        if "go" not in node:
            return None
        for it in sorted(node["ctors"], key=lambda i: (len(i["args"]), i["id"])):
            if not bound(it) or (it["kind"] == "convert" and not it.get("emitted")) or it.get("handed"):
                continue
            if it["kind"] == "convert":
                c = self.conv(it, depth)
                if c is not None:
                    return c
                continue
            if not self.ctor_ok(it):
                continue
            a = self.args(it, depth, self.variadic_ctor(node, it))
            if a is not None:
                return f"gk.{it['go']}({a})"
        return None

    def helpers(self, row_type):
        """The helper declarations the values asked for."""
        o = []
        if "rows" in self.uses:
            o += [f"// {row_type}: rows for every builder that takes a data table (docs/PROTOCOLS.md section 12).",
                  f"type {row_type} struct {{", "\tLabel string", "\tValue float64", "\tGap   gk.Option[float64]", "\tColor gk.Color", "}", "",
                  f"var {self.pre}sampleRows = []{row_type}{{{{\"a\", 1, gk.Some(2.0), gk.Color{{}}}}, {{\"b\", 3, gk.Option[float64]{{}}, gk.Color{{}}}}}}", ""]
        if self.handlers:
            o.append("// Handlers that do nothing, one per handler shape a builder takes.")
            o += [self.handlers[n][1] for n in sorted(self.handlers)]
            o.append("")
        return o


class StateArgs(GoSample):
    """gk_tests.StateArgs in Go: the sample's values, except the ones a call op cannot take
    outside a view build (elements, nodes, other handles)."""

    NO = ("entity", "handle", "child", "fragment", "node", "build", "stylefn", "action", "shim", "rows", "obj", "refmut")
    NO_IN = ("entity", "handle", "child", "fragment", "node", "build", "obj")

    def sval(self, d, depth=0):
        if d[0] in self.NO:
            return None
        if d[0] in ("opt", "ref", "from", "list") and d[1][0] in self.NO_IN:
            return None
        if d[0] == "into":
            s = self.m.intos[d[1]]
            if "go" not in s:
                return self.sval(s["members"][0]["desc"], depth + 1)
            if not self.put_ok(d):
                return None
            for t, md in self.into_members(s):
                v = self.sval(md, depth + 1)
                if v is not None:
                    return f"{t}({v})" if t in BASIC else v
            return None
        if d[0] == "rec":
            if any(self.sval(f["desc"], depth + 1) is None for f in self.m.records[d[1]]["fields"]):
                return None
        return self.val(d, depth)

    def sargs(self, it):
        vs = [self.sval(a["desc"]) for a in it["args"] if a["desc"][0] != "ctx"]
        return None if None in vs else ", ".join(vs)


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = "\n".join(lines) + "\n"
    with open(path, "w") as f:
        f.write(text)
    gofmt = shutil.which("gofmt")
    if gofmt:
        subprocess.run([gofmt, "-w", path], check=False)


def imports(text, extra=()):
    imps = set(extra)
    for pkg in ("time", "reflect", "math", "bytes", "os"):
        if re.search(rf"(?<![\w.]){pkg}\.[A-Za-z]", text):
            imps.add(pkg)
    if re.search(r"(?<![\w.])binary\.", text):
        imps.add("encoding/binary")
    std = sorted(i for i in imps if not i.startswith("gpuikit.dev"))
    ours = ['"gpuikit.dev/gk"'] + (['"gpuikit.dev/gk/s"'] if re.search(r"(?<![\w.])s\.[A-Z]", text) else [])
    return ["import ("] + [f'\t"{i}"' for i in std] + ([""] if std else []) + ["\t" + i for i in ours] + [")", ""]


