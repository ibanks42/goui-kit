class Enc:
    """Go encoders of payloads, as the Rust Wire impls write them: the inverse of gk_go.Go.rd."""

    def __init__(self, m, go):
        self.m, self.go = m, go
        self.fns, self.todo = {}, []

    def name(self, k, rt):
        t = (self.m.records if k == "rec" else self.m.denums)[rt]["go"]
        if (k, rt) not in self.fns:
            self.fns[(k, rt)] = None
            self.todo.append((k, rt))
        return f"enc{t}"

    def enc(self, d, v, dep=0, out=True):
        m, k = self.m, d[0]
        if dep > 8:
            raise Unsup("too deep")
        if k == "bool":
            return [f"w.flag({v})"]
        if k in ("int", "nonzero"):
            n = WIDTH[INT_WIRE.get(d[1], "u64")]
            return [f"w.u{n}(uint{n}({v}))"]
        if k == "f32":
            return [f"w.f32({v})"]
        if k == "f64":
            return [f"w.f64({v})"]
        if k == "char":
            return [f"w.u32(uint32({v}))"]
        if k == "str":
            return [f"w.text({v})"]
        if k == "leaf":
            if d[1] == "color":
                return [f"w.f32({v}.H)", f"w.f32({v}.S)", f"w.f32({v}.L)", f"w.f32({v}.A)"] if out else [f"encColor(w, {v})"]
            r = {"click_event": "encClick", "key_event": "encKey", "mouse_event": "encMouse"}.get(d[1])
            if r:
                return [f"{r}(w, {v})"]
            if d[1] in ("px", "rems"):
                return [f"w.f32({v})"]
            if d[1] == "range":
                return [f"w.u64(uint64({v}.Lo))", f"w.u64(uint64({v}.Hi))"]
            if d[1] == "duration":
                return [f"w.u32(uint32({v} / time.Millisecond))"]
            raise Unsup(f"leaf {d[1]}")
        if k == "enum":
            return [f"w.u16(uint16({v}))"]
        if k in ("denum", "rec"):
            return [f"{self.name(k, d[1])}(w, {v})"]
        if k in ("ref", "from", "refmut", "rcvec"):
            return self.enc(d[1], v, dep, out)
        if k == "opt":
            x = f"x{dep}"
            return [f"if {x}, ok := {v}.Get(); ok {{", "\tw.u8(1)"] + ["\t" + s for s in self.enc(d[1], x, dep + 1, out)] + \
                ["} else {", "\tw.u8(0)", "}"]
        if k in ("list", "arcslice", "iter"):
            x = f"x{dep}"
            return [f"w.u32(uint32(len({v})))", f"for _, {x} := range {v} {{"] + \
                ["\t" + s for s in self.enc(d[1], x, dep + 1, out)] + ["}"]
        if k == "array":
            x = f"x{dep}"
            return [f"for _, {x} := range {v} {{"] + ["\t" + s for s in self.enc(d[1], x, dep + 1, out)] + ["}"]
        if k == "rangeof":
            return self.enc(d[1], f"{v}[0]", dep, out) + self.enc(d[1], f"{v}[1]", dep, out)
        if k == "tuple":
            return [s for n, x in enumerate(d[1]) for s in self.enc(x, f"{v}.V{n}", dep, out)]
        if k in ("entity", "handle", "shim", "rows", "datum_rows", "obj"):
            return [f"w.u64(hidden({v}, 0).Uint())"]
        if k == "action":
            return [f"w.u32(uint32(hidden({v}, 0).Uint()))"]
        raise Unsup(f"{k} encoded")

    def fn(self, k, rt):
        m, go = self.m, self.go
        if k == "rec":
            rc = m.records[rt]
            R = rc["go"]
            o = [f"func enc{R}(w *wbuf, v gk.{R}) {{"]
            if rc.get("go_bad"):
                return o + [f'\tpanic("gk.{R} is not carried in Go")', "}", ""]
            fname = (lambda f: "V" + f["name"]) if rc["tuple"] else (lambda f: camel(f["name"]))
            for f in rc["fields"]:
                o += ["\t" + s for s in self.enc(f["desc"], f"v.{fname(f)}", 1, not rc["in"])]
            return o + ["}", ""]
        e = m.denums[rt]
        E = e["go"]
        units = go.unit_values(e)
        o = [f"func enc{E}(w *wbuf, v gk.{E}) {{", "\tswitch x := v.(type) {"]
        if units:
            o += [f"\tcase gk.{e['go_kind']}:", "\t\tw.u16(uint16(x))"]
        for v in e["variants"]:
            if not v.get("ok") or "go" not in v or v in units or v.get("go_bad"):
                continue
            try:
                if go.embeds(v):
                    f = v["fields"][0]
                    body = self.enc(f["desc"], "x." + go.gtype(f["desc"], not e["in"]).split("[")[0], 2, not e["in"])
                else:
                    body = [s for f in v["fields"] for s in self.enc(f["desc"], f"x.{go.vfield(v, f)}", 2, not e["in"])]
            except Unsup:
                continue
            o += [f"\tcase gk.{v['go']}:", "\t\t_ = x", f"\t\tw.u16({v['num']})"] + ["\t\t" + s for s in body]
        return o + ["\tdefault:", f'\t\tpanic(fmt.Sprintf("enc{E}: a %T the test cannot encode", v))', "\t}", "}", ""]

    def funcs(self):
        o = []
        while self.todo:
            k, rt = self.todo.pop(0)
            self.fns[(k, rt)] = self.fn(k, rt)
        for key in sorted(self.fns, key=lambda kr: (self.m.records if kr[0] == "rec" else self.m.denums)[kr[1]]["go"]):
            o += self.fns[key]
        return o

    def readable(self, d, out=True, depth=0):
        """True when the Go package reads the sample's value of d (the variant the sample sends,
        every record field) without stopping, and this test can encode it again."""
        m, k = self.m, d[0]
        if depth > 8:
            return False
        try:
            self.go.rd(d, out)
            self.enc(d, "v", 0, out)
        except (Unsup, KeyError):
            return False
        if k == "rec":
            rc = m.records[d[1]]
            return not rc.get("go_bad") and all(self.readable(f["desc"], not rc["in"], depth + 1) for f in rc["fields"])
        if k == "denum":
            e = m.denums[d[1]]
            v = gk_tests.pick_variant(m, e)
            if v is None or not v.get("ok") or "go" not in v or v.get("go_bad"):
                return False
            if v in self.go.unit_values(e):
                return True
            return all(self.readable(f["desc"], not e["in"], depth + 1) for f in v["fields"])
        if k in ("ref", "from", "refmut", "rcvec", "opt", "list", "arcslice", "iter", "array", "rangeof"):
            return self.readable(d[1], out, depth + 1)
        if k == "tuple":
            return all(self.readable(x, out, depth + 1) for x in d[1])
        return True


def go_states(m, go, sa, skip_calls):
    """gk_tests.states in Go: per state type the Go package generated, its constructor (with the
    builder chain) and the methods it has, in gk_go.Go.state's order."""
    ok = lambda i: i["status"] == "bridged"  # noqa: E731
    out = []
    for key in sorted(m.states, key=lambda k: m.states[k].get("stem", "") or ""):
        st = m.states[key]
        S = st.get("stem")
        if not S:
            continue
        if "go" not in st:
            out.append({"stem": S, "skip": "no Go type"})
            continue
        G = st["go"]
        ctor = None
        for it in sorted([i for i in st["ctors"] if ok(i)], key=lambda i: i["stem"]):
            if any(a["desc"][0] in ("shim", "rows") for a in it["args"]):
                continue
            if "go" not in it or it["id"] not in go.mapped:
                continue
            a = sa.sargs(it)
            if a is not None:
                ctor = f"gk.{it['go']}(cx{', ' + a if a else ''})"
                break
        if ctor is None:
            why = "its constructor takes a row source (core/tests/rows)" if any(
                a["desc"][0] in ("shim", "rows") for i in st["ctors"] for a in i["args"]) else \
                "no constructor with arguments this test can make" if any(
                    ok(i) and "go" in i and i["id"] in go.mapped for i in st["ctors"]) else \
                "no constructor in Go" if any(ok(i) for i in st["ctors"]) else "no constructor with arguments this test can make"
            out.append({"stem": S, "skip": why})
            continue
        builders = sorted([i for i in st["builders"] if ok(i)], key=lambda i: i["name"])
        chain, nb = "", 0
        for it in builders:
            if it["id"] not in go.mapped:
                continue
            a = sa.sargs(it)
            if a is not None:
                chain += f".{camel(it['name'])}({a})"
                nb += 1
        if builders:
            chain += ".Build()"
        names = set()
        groups = {"reads": [], "calls": [], "writes": []}
        for group in ("reads", "calls", "writes"):
            for it in sorted([i for i in st.get(group, []) if ok(i)], key=lambda i: i["name"]):
                name = camel(it["name"])
                if name in names or it["id"] not in go.mapped:
                    continue
                names.add(name)
                a = sa.sargs(it)
                if a is None:
                    continue
                if group != "writes" and it.get("ret") and sa.stops(it["ret"]):
                    groups[group].append((name, "stop"))
                    continue
                if group != "reads" and f"{S}.{it['name']}" in skip_calls:
                    groups[group].append((name, None))
                    continue
                groups[group].append((name, a))
        events = []
        for ev in st["events"]:
            name = "On" + camel(snake(ev["name"]))
            if name in names or ev["id"] not in go.mapped:
                continue
            names.add(name)
            events.append((name, m.shapes[ev["shape"]]))
        out.append({"stem": S, "go": G, "field": "st" + G, "make": ctor + chain, "builders": nb, **groups, "events": events})
    return out


