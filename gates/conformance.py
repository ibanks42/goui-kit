#!/usr/bin/env python3
"""Generate and verify one-function visual conformance gallery pages for Rust and Go.

What it gates (`--check`):
  Keeps the generated conformance gallery consistent across four artifacts:
  - `ref/src/bin/gallery/conf.rs` (pure-Rust GPUI-kit pages)
  - `ref/gallery/conf.txt` (page registry appended after `ref/gallery/pages.txt`)
  - `examples/go/gallery/conf.go` (matching Go pages plus complete `pageIDs` ordering)
  - `gates/gallery-go-pending.txt` (generated block of Rust pages Go cannot yet express)

How it measures and why the comparison is fair:
  For every bound element constructor, element method, and shared trait method in
  `api/gk.api.json.gz` whose arguments can be synthesized deterministically (numbers, lengths,
  colors, durations, strings, bools, children, unit enums), this script emits a side-by-side
  `pair(base, el)` in both Rust and Go using identical synthetic values. Placing the plain
  baseline element next to the modified copy inside fixed 240 px boxes makes visual differences
  immediately visible while ensuring both languages construct the exact same widget tree.
  Pages that panic in upstream Rust are excluded via `gates/conformance-skip.txt`; pages with
  `go:<id>` are kept in Rust and quarantined only in Go.

What PASS means (`--check`, exit 0):
  `conf.txt` and `conf.rs` define the exact same set of page IDs, every Go page in `conf.go`
  exists in `conf.txt`, and `conf.go`'s `pageIDs` list matches `pages.txt` followed by
  `conf.txt` in exact order. Staleness against the current API description is also reported in
  the GATE line.
"""
import gzip
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = "api/gk.api.json.gz"
OUT_RS = "ref/src/bin/gallery/conf.rs"
OUT_TXT = "ref/gallery/conf.txt"
OUT_GO = "examples/go/gallery/conf.go"
PAGES_TXT = "ref/gallery/pages.txt"
PENDING_GO = "gates/gallery-go-pending.txt"
PENDING_BEGIN = "# --- generated by gates/conformance.py: conformance pages Rust has and Go cannot write yet ---"
PENDING_END = "# --- end of the generated block ---"
SKIP = "gates/conformance-skip.txt"
# Minimal visible content added to container/control types so styling changes show up in screenshots.
DRESS = {"Button": ("label", "Button"), "Checkbox": ("label", "Checkbox"), "Switch": ("label", "Switch"),
         "Radio": ("label", "Radio"), "Tag": ("child", "Tag"), "Avatar": ("name", "Ada Lovelace"),
         "Progress": ("value", None), "Badge": ("count", None), "Link": ("child", "Link"),
         "Div": ("child", "Div")}
# Preferred representative types when choosing one concrete element to host each shared trait method.
FIRST = ["Button", "Tag", "Checkbox", "Switch", "Label", "Div"]

def snake(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()

def tail(path):
    return path.split("<", 1)[0].rsplit("::", 1)[-1]

class NoSample(Exception):
    pass

LENGTHS = {"length": "Length", "definite_length": "DefiniteLength", "absolute_length": "AbsoluteLength"}

def rust_arg(desc, api, text=None, ident="conf-a"):
    """Synthesize a deterministic Rust expression for one argument descriptor, or raise NoSample."""
    k = desc[0]
    if k == "leaf":
        if desc[1] == "id":
            return json.dumps(ident)
        if desc[1] == "px":
            return "gpui_kit::px(40.)"
        if desc[1] == "color":
            return "gpui_kit::hsla(0.6, 0.7, 0.5, 1.0)"
        if desc[1] == "duration":
            return "std::time::Duration::from_millis(3)"
        if desc[1] in LENGTHS:
            return f"gpui_kit::{LENGTHS[desc[1]]}::from(gpui_kit::px(40.))"
        raise NoSample(f"leaf {desc[1]}")
    if k == "bool":
        return "true"
    if k == "str" and desc[1] == "into":
        return json.dumps(text or "Sample")
    if k == "int":
        return "3"
    if k in ("f32", "f64"):
        return "40.0"
    if k == "child":
        return f'gpui_kit::div().child("{text or "Child"}").into_any_element()'
    if k == "enum":
        e = api["enums"].get(desc[1])
        units = [v for v in (e or {}).get("variants", []) if v.get("shape") == "unit" and v.get("ok", True)]
        if not units:
            raise NoSample("enum without a unit variant")
        # Pick the second unit variant when available so the call visibly departs from the default variant.
        return f"{e['rust']}::{units[1 if len(units) > 1 else 0]['name']}"
    raise NoSample(k if k != "str" else f"str {desc[1]}")

def enum_member(desc, api):
    """Return the chosen unit-enum variant name matching rust_arg's selection rule."""
    e = api["enums"][desc[1]]
    units = [v for v in e["variants"] if v.get("shape") == "unit" and v.get("ok", True)]
    return units[1 if len(units) > 1 else 0]["name"]

INTS = {"int", "uint", "i32", "u32", "i64", "u64", "u16", "i16", "u8", "i8", "isize", "usize", "uintptr"}

GO_INITIALISMS = {"id", "url", "uri", "json", "html", "http", "svg", "css", "api", "ascii", "utf8"}

def go_camel(name):
    """Convert snake_case Rust names to exported Go CamelCase while preserving known initialisms."""
    parts = [p for p in name.split("_") if p]
    return "".join(p.upper() if p in GO_INITIALISMS else p[:1].upper() + p[1:] for p in parts)

def go_params(text):
    """Parse a Go parameter list (including grouped types like `a, b float32`) into (name, type) pairs."""
    raw, depth, cur = [], 0, ""
    for ch in text:
        depth += ch in "([{"
        depth -= ch in ")]}"
        if ch == "," and depth == 0:
            raw.append(cur)
            cur = ""
        else:
            cur += ch
    raw.append(cur)
    out, pending = [], []
    for p in raw:
        p = p.strip()
        if not p:
            continue
        bits = p.split(None, 1)
        if len(bits) == 1:
            pending.append(bits[0])
            continue
        name, typ = bits
        if typ.startswith("..."):
            break
        for n in pending + [name]:
            out.append((n, typ.strip()))
        pending = []
    return out

def split_go(text):
    # Rewrite flat `gk.*` references into split subpackages (`kit`, `overlay`, etc.) and run gofmt.
    import subprocess  # noqa: PLC0415
    sys.path.insert(0, os.path.join(REPO, "gen"))
    import gk_split  # noqa: PLC0415
    tmp = os.path.join(gk_split.OUT, "conf.go")
    open(tmp, "w").write(text)
    gk_split.gosplit("migrate", os.path.join(gk_split.OUT, "table.json"), tmp)
    subprocess.run(["gofmt", "-w", tmp], check=True)
    return open(tmp).read()

class GoPackage:
    """Scrapes flat generated Go files to index element types, constructors, methods, and enum constants."""
    def __init__(self, d):
        src = ""
        for f in sorted(os.listdir(d)):
            if f.endswith(".go") and not f.endswith("_test.go"):
                src += open(os.path.join(d, f)).read() + "\n"
        self.types, self.funcs, self.methods, self.enums, self.variants = {}, {}, {}, {}, {}
        for m in re.finditer(r"^// (\w+) is (gpui_kit::[\w:<>, ]+)\.\n(?://[^\n]*\n)*type \1 ", src, re.M):
            self.types[m.group(2)] = m.group(1)
        for m in re.finditer(r"^func (\w+)\((.*?)\) (\w+)\s+\{", src, re.M):
            self.funcs[m.group(1)] = (go_params(m.group(2)), m.group(3))
        for m in re.finditer(r"^func \(\w+ (\w+)\) (\w+)\((.*?)\) (\w+)\s+\{", src, re.M):
            if m.group(4) == m.group(1):
                self.methods.setdefault(m.group(1), {})[m.group(2)] = go_params(m.group(3))
        for m in re.finditer(r"^const \(\n(.*?)^\)", src, re.M | re.S):
            for c in re.finditer(r"^\s*(\w+)\s+(\w+) = [^\n/]*(?://\s*([\w:]+))?", m.group(1), re.M):
                self.enums.setdefault(c.group(2), []).append(c.group(1))
                if c.group(3):
                    self.variants[c.group(3)] = (c.group(1), c.group(2))

def go_enum(desc, typ, gpkg, api):
    e = api["enums"][desc[1]]
    member = enum_member(desc, api)
    hit = gpkg.variants.get(f"{e['rust']}::{member}")
    if hit and (hit[1] == typ or (typ.endswith("Into") and hit[1].startswith(typ[:-4]))):
        return "gk." + hit[0]
    want = member.replace("_", "").lower()
    cands = [c for c in gpkg.enums.get(typ, []) if c.lower().endswith(want)]
    if cands:
        return "gk." + min(cands, key=len)
    raise NoSample(f"enum {typ} has no member for {member}")

def go_arg(desc, typ, gpkg, api, text=None, ident="conf-a"):
    k = desc[0]
    if k == "leaf" and desc[1] == "id" and typ in ("ID", "string"):
        return json.dumps(ident)
    if k == "leaf" and desc[1] == "px" and typ in ("float32", "Length", "Pixels"):
        return "40" if typ == "float32" else "gk.Px(40)"
    if k == "leaf" and desc[1] in LENGTHS and typ == "Length":
        return "gk.Px(40)"
    if k == "leaf" and desc[1] == "color" and typ in ("Color", "Fill"):
        return "gk.HSLA(0.6, 0.7, 0.5, 1)"
    if k == "leaf" and desc[1] == "duration" and typ == "time.Duration":
        return "3 * time.Millisecond"
    if k == "bool" and typ == "bool":
        return "true"
    if k == "str" and typ == "string":
        return json.dumps(text or "Sample")
    if k == "int" and typ in GO_INTS:
        return "3"
    if k in ("f32", "f64") and typ in ("float32", "float64"):
        return "40"
    if k == "child" and typ == "Element":
        return f'gk.Div().Text("{text or "Child"}")'
    if k == "enum":
        return go_enum(desc, typ, gpkg, api)
    raise NoSample(f"a {k} argument against the Go type {typ}")

GO_INTS = {"int", "uint", "int8", "int16", "int32", "int64", "uint8", "uint16", "uint32", "uint64", "uintptr"}

def main():
    argv = sys.argv[1:]
    opt = lambda name: argv[argv.index(name) + 1] if name in argv else None
    api = json.load(gzip.open(os.path.join(REPO, API)))
    items = {i["id"]: i for i in api["items"]}
    gpkg = GoPackage(os.path.join(REPO, opt("--go-package") or "gen/out/build.go/flat"))
    skip = {}
    if os.path.exists(os.path.join(REPO, SKIP)):
        for line in open(os.path.join(REPO, SKIP)):
            if line.strip() and not line.startswith("#"):
                pid, _, why = line.partition("|")
                skip[pid.strip()] = why.strip()

    elements = {p: n for p, n in api["nodes"].items()
                if n.get("element") and "crate::values::" not in p and "crate::rt::" not in p}
    last = {}
    for p in elements:
        last.setdefault(tail(p), []).append(p)

    def label(path):
        name = tail(path)
        return name if len(last[name]) == 1 else f"{path.split('::')[1]}::{name}"

    def bound(ids):
        return [items[i] for i in ids if i in items and items[i]["status"] == "bound" and not i.endswith("::(handed)")]

    def rust_call(it, path, recv, text=None, ident="conf-a"):
        args = [rust_arg(a["desc"], api, text, ident) for a in it["args"]]
        callee = it["callee"].replace("<E as ", f"<{path} as ")
        return f"{callee}({', '.join(([recv] if recv else []) + args)})"

    def go_ctor(it, path, ident):
        gt = gpkg.types.get(path)
        if gt is None or not gt.endswith("El"):
            raise NoSample("the Go package has no such element type")
        if it.get("free"):
            name = go_camel(it["name"])
        else:
            name = gt[:-2] if it["name"] == "new" else gt[:-2] + go_camel(it["name"])
        if name not in gpkg.funcs or gpkg.funcs[name][1] != gt:
            raise NoSample(f"the Go package has no constructor {name}")
        params = gpkg.funcs[name][0]
        if len(params) != len(it["args"]):
            raise NoSample(f"{name}: the Go package takes {len(params)} arguments, the description {len(it['args'])}")
        return f"gk.{name}({', '.join(go_arg(a['desc'], p[1], gpkg, api, None, ident) for a, p in zip(it['args'], params))})"

    def go_call(it, path, text=None):
        gt = gpkg.types.get(path)
        if gt is None:
            raise NoSample("the Go package has no such element type")
        name = go_camel(it["name"])
        fields = gpkg.methods.get(gt, {})
        if name not in fields:
            raise NoSample(f"the Go package has no {gt}.{name}")
        params = fields[name]
        if len(params) != len(it["args"]):
            raise NoSample(f"{gt}.{name}: the Go package takes {len(params)} arguments, the description {len(it['args'])}")
        return f".{name}({', '.join(go_arg(a['desc'], p[1], gpkg, api, text) for a, p in zip(it['args'], params))})"

    def samplable(it):
        try:
            for a in it["args"]:
                rust_arg(a["desc"], api)
            return True
        except NoSample:
            return False

    # Choose one default constructor and optional dressing method for every constructible element type.
    setup = {}
    for path, node in elements.items():
        ctors = [c for c in bound(node["ctors"]) if samplable(c) and c.get("kind") != "convert"]
        default = (next((c for c in ctors if c["name"] in ("new", snake(tail(path)))), None)
                   or next((c for c in ctors if not c["args"]), None) or (ctors[0] if ctors else None))
        if default is None:
            continue
        dress = None
        want = DRESS.get(tail(path))
        if want:
            cands = bound(node["ops"]) + [o for t in node["tables"] for o in bound(api["traits"].get(t, {}).get("ops", []))]
            dress = next((o for o in cands if o["name"] == want[0] and samplable(o)), None)
        setup[path] = (default, dress, want[1] if want else None)

    # Order elements so preferred basic widgets in FIRST host shared trait methods before specialized types.
    def rank(p):
        name = tail(p)
        plain = "::component::" in p or p.count("::") == 1
        return (FIRST.index(name) if name in FIRST and plain else len(FIRST), p)
    order = sorted(setup, key=rank)
    jobs = []
    counts = {"functions": 0, "no constructor": 0, "skipped": 0}
    no_sample = {}
    seen_items = set()

    # Filter out duplicate IDs, type-changing convert methods, unsamplable args, and skipped pages.
    def consider(pid, path, it):
        if it["id"] in seen_items:
            return
        seen_items.add(it["id"])
        counts["functions"] += 1
        if path not in setup:
            counts["no constructor"] += 1
            return
        if it["kind"] == "convert":
            no_sample["type-changing method"] = no_sample.get("type-changing method", 0) + 1
            return
        try:
            for a in it["args"]:
                rust_arg(a["desc"], api)
        except NoSample as e:
            no_sample[str(e)] = no_sample.get(str(e), 0) + 1
            return
        if pid in skip:
            counts["skipped"] += 1
            return
        jobs.append((pid, path, it))

    # First collect inherent constructors and methods per element, then each shared trait op once on
    # the highest-ranked element implementing that trait without an inherent method of the same name.
    for path in sorted(elements):
        node = elements[path]
        for it in bound(node["ctors"]):
            consider(f"{label(path)}.{it['name']}", path, it)
        for it in bound(node["ops"]):
            consider(f"{label(path)}.{it['name']}", path, it)
    for tpath in sorted(api["traits"]):
        rep = next((p for p in order if tpath in elements[p]["tables"]), None)
        tname = tpath.split(" where ")[0].rsplit("::", 1)[-1] + ("+" if " where " in tpath else "")
        for it in bound(api["traits"][tpath]["ops"]):
            r = next((p for p in order if tpath in elements[p]["tables"] and setup[p][0].get("kind") != "convert"
                      and not any(items.get(o, {}).get("name") == it["name"] for o in elements[p]["ops"])), rep)
            consider(f"{tname}.{it['name']}", r or "-", it)

    # Emit paired (base, modified) calls for Rust and, where Go exposes the matching signature, for Go.
    # Use distinct IDs ("conf-a" vs "conf-b") so sibling GPUI elements never collide on element ID.
    rs, txt = [], []
    gos, go_why, go_pending = [], {}, []
    used = set()
    for pid, path, it in jobs:
        if pid in used:
            continue
        used.add(pid)
        default, dress, dtext = setup[path]
        is_ctor = it["kind"] == "ctor"
        base = rust_call(default, path, None, None, "conf-a")
        if dress is not None:
            base = rust_call(dress, path, base, dtext)
        el = rust_call(it if is_ctor else default, path, None, None, "conf-b")
        if dress is not None and it is not dress:
            el = rust_call(dress, path, el, dtext)
        if not is_ctor:
            el = rust_call(it, path, el)
        rs.append(f'        "{pid}" => pair({base}, {el}),')
        txt.append(f"{pid} |  | {it['id']}")
        try:
            d = go_call(dress, path, dtext) if dress is not None else ""
            gbase = go_ctor(default, path, "conf-a") + d
            gel = go_ctor(it if is_ctor else default, path, "conf-b")
            if dress is not None and it is not dress:
                gel += d
            if not is_ctor:
                gel += go_call(it, path)
            if "go:" + pid in skip:
                raise NoSample("quarantined: " + skip["go:" + pid])
            gos.append((pid, "conf" + "".join(w[:1].upper() + w[1:] for w in re.split(r"\W+", pid) if w), gbase, gel))
        except NoSample as e:
            r = re.sub(r"constructor \w+|\w+\.\w+", "such function", str(e)) if "has no" in str(e) else re.sub(r"^\S+: ", "", str(e))
            go_why[r] = go_why.get(r, 0) + 1
            go_pending.append(f"{pid} | {e}")

    head = f"Generated by gates/conformance.py from {API}. Do not edit: run that script."
    rust = f"""//! {head}
//! One page per bound function: the element as its constructor makes it, and with that one
//! function applied, calling GPUI-kit natively. The Go twin is examples/go/gallery/conf.go.
//! One page per line: a compiler error's line names its page (line - {{FIRST_LINE}} into conf.txt).
#![allow(clippy::all, deprecated)]
#![cfg_attr(rustfmt, rustfmt_skip)]
use gpui_kit::component::h_flex;
use gpui_kit::{{AnyElement, IntoElement, ParentElement, Styled, div, px}};

fn pair(base: impl IntoElement, el: impl IntoElement) -> AnyElement {{
    h_flex()
        .gap_3()
        .child(div().w(px(240.)).child(base))
        .child(div().w(px(240.)).child(el))
        .into_any_element()
}}

/// The page of a conformance id, or None if the id is not one.
pub fn page(id: &str) -> Option<AnyElement> {{
    Some(match id {{
"""
    rust = rust.replace("{FIRST_LINE}", str(rust.count("\n") + 1)) + "\n".join(rs) + """
        _ => return None,
    })
}
"""
    text = (f"# {head}\n# Conformance pages, one per bound function, in the format of pages.txt; the third column is\n"
            f"# the description's id of the function. They follow the hand-written pages in the gallery's order.\n"
            + "\n".join(txt) + "\n")

    hand = []
    for line in open(os.path.join(REPO, PAGES_TXT)):
        line = line.strip()
        if line and not line.startswith("#"):
            hand.append(line.split("|")[0].strip())
    all_ids = hand + [l.split("|")[0].strip() for l in txt]
    goids = "".join(f"\t{json.dumps(i)},\n" for i in all_ids)
    gotab = "".join(f"\t{{{json.dumps(pid)}, {fn}}},\n" for pid, fn, _, _ in gos)
    gofns = "".join(f"""
func {fn}(a *App, cx *gk.Cx) gk.Element {{
\tbase := {gbase}
\tel := {gel}
\treturn confPair(base, el)
}}
""" for pid, fn, gbase, gel in gos)
    golang = f"""// {head}
// One page per bound function the Go package declares today: the element as its constructor
// makes it, and with that one function applied. The Rust twin is ref/src/bin/gallery/conf.rs.

package main

import (
\t"time"

\t"gpuikit.dev/gk"
\t"gpuikit.dev/gk/s"
)

var _ = time.Millisecond

// pageIDs are the ids of every page in the gallery's order: ref/gallery/pages.txt, then
// ref/gallery/conf.txt (a Go program cannot embed a file from outside its module).
var pageIDs = []string{{
{goids}}}

func confPair(base, el gk.Element) gk.Element {{
\treturn gk.HFlex(s.Gap3).Child(gk.Div().W(gk.Px(240)).Child(base)).Child(gk.Div().W(gk.Px(240)).Child(el))
}}

var confPages = []Page{{
{gotab}}}
{gofns}"""
    # Preserve any hand-written pending entries above PENDING_BEGIN and regenerate the block below it.
    pend_path = os.path.join(REPO, PENDING_GO)
    pend_old = open(pend_path).read() if os.path.exists(pend_path) else ""
    if PENDING_BEGIN in pend_old:
        pend_keep = pend_old.split(PENDING_BEGIN)[0]
    else:
        pend_keep = pend_old if pend_old.endswith("\n") or not pend_old else pend_old + "\n"
    pending = pend_keep + PENDING_BEGIN + "\n" + "".join(l + "\n" for l in go_pending) + PENDING_END + "\n"

    files = {OUT_RS: rust, OUT_TXT: text, OUT_GO: split_go(golang), PENDING_GO: pending}
    if "--check" in argv:
        # Verify structural consistency across generated files and report if any file lags behind current inputs.
        read = lambda p: open(os.path.join(REPO, p)).read() if os.path.exists(os.path.join(REPO, p)) else ""
        in_txt = [l.split("|")[0].strip() for l in read(OUT_TXT).splitlines() if l.strip() and not l.startswith("#")]
        in_rs = re.findall(r'^        "([^"]+)" => pair\(', read(OUT_RS), re.M)
        in_go = re.findall(r'^\t\{"([^"]+)", conf\w+\},$', read(OUT_GO), re.M)
        go_ids = re.findall(r'^\t("[^"]+"),$', read(OUT_GO).split("func confPair")[0], re.M)
        bad = []
        if set(in_txt) != set(in_rs):
            bad.append(f"{OUT_TXT} and {OUT_RS} name different pages")
        if set(in_go) - set(in_txt):
            bad.append(f"{OUT_GO} has pages {OUT_TXT} does not")
        if [json.loads(i) for i in go_ids] != all_ids:
            bad.append(f"{OUT_GO} lists other page ids than {PAGES_TXT} and {OUT_TXT}")
        behind = [p for p, c in files.items() if read(p) != c]
        note = (f"; behind the description or the package in {' '.join(behind)}"
                ": run gates/conformance.py, "
                f"rebuild ref-gallery, gates/gallery.sh --record" if behind else "; current")
        print(f"GATE conformance generated {'FAIL' if bad else 'PASS'} {len(in_txt)} pages, {len(in_go)} of them in Go"
              + ("; " + "; ".join(bad) if bad else "") + note)
        return 1 if bad else 0
    for p, c in files.items():
        open(os.path.join(REPO, p), "w").write(c)
    print(f"conformance: {counts['functions']} bound constructors and builders of element types in {API}: "
          f"{len(used)} pages in Rust, {len(gos)} of them also in Go; without a page: "
          f"{counts['no constructor']} on types with no constructor this script can call, "
          f"{sum(no_sample.values())} with an argument it cannot make yet, {counts['skipped']} quarantined")
    for r, n in sorted(no_sample.items(), key=lambda kv: -kv[1]):
        print(f"  no sample, {n}: {r}")
